# [개념] break로 반복 중단하기
for i in range(1, 11):
    if i == 5:
        break  # 즉시 종료
    print(i)
# 출력: 1, 2, 3, 4

# [개념] continue로 회차 건너뛰기
for i in range(1, 7):
    if i % 2 == 0:
        continue  # 이번 회차 건너뜀
    print(i)
# 출력: 1, 3, 5

# [정리] break와 continue 구분
# 구분     | break        | continue
# 하는 일  | 반복 전체 종료 | 이번 회차 건너뜀
# 이후 흐름 | 바깥으로 나감  | 다음 회차로 계속
# 쓰는 목적 | 찾았으니 그만  | 거르고 계속


