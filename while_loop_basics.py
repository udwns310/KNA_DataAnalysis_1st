# Q1. while 반복 안에서 갱신(예: count += 1)을 깜빡 빠뜨리면 어떻게 되나요?
# -> A. 조건이 영원히 참으로 남아 무한 루프가 됨. 화면에 같은 값이 끝없이 찍히거나
#       아예 멈춘 것처럼 보이는데 사실은 계속 도는 중 - Ctrl+C로 강제 중단해야 함
# count = 1
# while count <= 3:
#     print(count)
# # count를 바꾸는 줄이 없어서 count는 계속 1로 남고, 조건도 계속 참 -> 무한 반복

# Q2. while 문 안에서 continue를 쓰면 for 문과 똑같이 안전한가요?
# -> A. 아니요. for는 continue를 만나도 다음 값으로 자동으로 넘어가지만, while은
#       continue가 그 아래 있는 갱신 코드까지 건너뛰어 버려서 조건 변수가 그대로 남을 수
#       있음. 그러면 조건이 계속 참으로 남아 무한 루프가 됨
# i = 0
# while i < 5:
#     if i == 2:
#         continue      # i가 2일 때 아래 i += 1을 건너뛰고 바로 조건 검사로 돌아감
#     print(i)
#     i += 1
# # i가 2에서 절대 안 바뀌고 continue만 반복 -> 무한 루프

# Q3. 반복문이 겹쳐 있을 때 안쪽에서 break를 걸면 바깥쪽 반복문까지 같이 끝나나요?
# -> A. 아니요. break는 자기가 속한 가장 안쪽 반복문 하나만 빠져나가고, 바깥쪽 반복문은
#       아무 일 없었다는 듯 계속 돎
for outer in range(3):
    for inner in range(3):
        if inner == 1:
            break
        print("바깥", outer, "안쪽", inner)
# 안쪽 반복은 inner==1에서 매번 끊기지만, 바깥 반복(outer)은 0,1,2 전부 돎

