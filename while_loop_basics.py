# 시작 상태 | 조건 변수의 출발값 정하기
# 종료 조건 | 멈출 상태의 반대를 조건식으로
# 갱신 방법 | 종료를 향해 값 바꾸기


print("\n===================== 실습 1. while로 목표값 도달까지 반복하기 =====================")
