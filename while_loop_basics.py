# 시작값    | 변수가 반복 전 정해짐 | 오작동
# 종료 조건  | 언젠가 거짓이 됨     | 무한 루프
# 갱신      | 거짓 방향으로 값 변경  | 무한 루프

# [강사님께 질문하기] while이 멈추지 못하고 계속 돌면, 화면만 멈춘 것처럼 보이는 건가요,
