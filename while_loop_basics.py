# - while은 조건이 거짓이 되어야 멈춤
# - 언젠가 거짓이 될 조건을 반드시 둘 것
# - 조건 값과 거짓으로 향하는 변화가 함께 필요

# [개념] 반복 변수 갱신과 무한 루프
