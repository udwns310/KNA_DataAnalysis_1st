# [개념] 최댓값·최솟값 찾기 - 왜 0이 아니라 "첫 값"에서 시작할까
readings = [-30, -12, -45, -8]  # 예시: 측정값이 전부 음수인 경우
wrong_max = 0  # 0에서 시작하면
for v in readings:
    if v > wrong_max:
        wrong_max = v
print(wrong_max)  # 0 (전부 음수라 진짜 최댓값 -8보다 0이 더 커서 엉뚱한 값이 남음)

correct_max = readings[0]  # 첫 값에서 시작하면
for v in readings[1:]:
    if v > correct_max:
        correct_max = v
print(correct_max)  # -8 (진짜 최댓값)

