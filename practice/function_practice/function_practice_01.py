# =====================================================================
# [기본문제] 실습 2. 다중 매개변수로 센서값 계산하기
# =====================================================================
def station_report(name, temp):
    print(name, temp, "도")

station_report("모터", 78)  # 모터 78 도
station_report("펌프", 92)  # 펌프 92 도

# ④ 인자 순서를 바꾸면?
station_report(78, "모터")  # 78 모터 도 - 매개변수 자리가 뒤바뀌어 그대로 뒤바뀐 값이 들어감
