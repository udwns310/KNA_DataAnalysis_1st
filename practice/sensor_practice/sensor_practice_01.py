        f"가동 중 {stuck_len}행 연속 동일값(1.6)인데 같은 구간 VIB_H는 계속 변동 - 다른 컬럼과 동행하지 않음",
        "가동 중 정상 변동, 정지 시 대기 전류 수준으로 함께 떨어짐",
