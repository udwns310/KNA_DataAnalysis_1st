# 실습 - 이상 구간 원인 분류
# 목표: 여러 컬럼의 이상 구간을 찾아 유형(설비 이상·센서 이상·판단 보류)과 근거를 판정
# CASE A: MTR02 모터 계통 컬럼 전체 / CASE B: HYD02·FUR02 유압·가열로 계통
#
# * 이 실습 데이터는 study/sensor_faults.py에서 배운 드리프트·고착·스파이크 패턴을
#   숫자로 재현한 예시용 데이터이며, 실제 설비의 센서 실측값은 아님
import pandas as pd


def max_repeat_run(values):
    values = list(values)
    run = best = 1
    for i in range(1, len(values)):
        if values[i] == values[i - 1]:
            run += 1
            best = max(best, run)
        else:
            run = 1
    return best


