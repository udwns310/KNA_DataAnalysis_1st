running = mtr02[mtr02["MTR02_RUN"] == 1]
value_cols = ["MTR02_VIB_H", "MTR02_VIB_V", "MTR02_CURRENT", "MTR02_TEMP"]
repeat_in_run = {col: max_repeat_run(running[col]) for col in value_cols}
