# STEP 3. 세 질문으로 원인 확정
# ① 동시 반응 - VIB_V가 멈춘 구간에서 VIB_H도 함께 멈췄는지 확인
stuck_start = 5
stuck_len = repeat_in_run["MTR02_VIB_V"]
vib_h_during_stuck = mtr02["MTR02_VIB_H"].iloc[stuck_start:stuck_start + stuck_len]
print(vib_h_during_stuck.tolist(), vib_h_during_stuck.nunique())
# - VIB_V는 5행 연속 1.6으로 고착됐는데, 같은 구간의 VIB_H는 값이 계속 바뀜(nunique > 1) -
#   "다른 컬럼은 계속 변동"이라는 고착의 특징과 정확히 일치

# ② 물리 타당성 - 정지 구간(RUN=0)에서 진동·전류가 물리 기준값(0 근처)에 가까운지 확인
