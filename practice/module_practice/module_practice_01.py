# [기본문제] 실습 1. import 세 방식으로 모듈 가져오기
# =====================================================================

# ① import 모듈명으로 통째로 가져와 모듈명.기능() 으로 사용
import math
print(math.sqrt(16), math.ceil(4.3))  # 4.0 5

# ② from 모듈 import 기능 으로 일부만 가져와 모듈명 없이 사용
from math import sqrt, ceil
print(sqrt(16), ceil(4.3))  # 4.0 5

# ③ import 모듈 as 별명 으로 별명.기능() 으로 사용
import math as m
print(m.sqrt(16), m.ceil(4.3))  # 4.0 5

# ④ 세 방식의 출력이 같은지 확인 -> 모두 4.0 5 로 동일함
