# 실습2 - AGC 원인 역추적 (제어 대상 vs 조작량·부하·설비 상태)
# 목표: "출측 두께(제어 대상)"는 AGC 덕분에 안정적으로 보여도, 그 두께를 지키기 위해
#      점점 커지는 "롤 갭 보정폭·압연 하중·주모터 전류"가 롤 열화의 선행 신호임을 확인
#
# * 이 실습 데이터는 슬라이드의 "제어 대상·조작량과 초기 열화 신호" 개념(study/
#   steel_process_steelmaking.py 참고)을 숫자로 재현한 예시용 데이터이며, 실제 설비의
#   센서 실측값은 아님
import pandas as pd

# STEP 1. 한 압연 캠페인(롤 교체 전후 20패스)의 예시 데이터 준비
pass_no = list(range(1, 21))

# 압연 하중(ton) - 1~12패스는 롤이 마모되며 점진적으로 상승, 13패스에 새 롤로 교체되며
# 급락한 뒤 다시 상승(톱니 패턴)
load = [830, 836, 842, 848, 854, 860, 866, 872, 878, 884, 890, 896,
        828, 834, 840, 846, 852, 858, 864, 870]

# 주모터 전류(A) - 같은 조건에서 하중과 함께 점진적으로 상승, 교체 시점에 함께 급락
current = [610, 613, 616, 619, 622, 625, 628, 631, 634, 637, 640, 643,
           606, 609, 612, 615, 618, 621, 624, 627]

# 롤 갭 보정폭(mm) - AGC가 두께를 지키려고 갭을 점점 더 크게 보정, 교체 시점에 초기화
gap_comp = [0.020, 0.026, 0.032, 0.038, 0.044, 0.050, 0.056, 0.062, 0.068, 0.074, 0.080, 0.086,
            0.018, 0.024, 0.030, 0.036, 0.042, 0.048, 0.054, 0.060]

# 출측 두께(mm) - 목표 2.30mm 근처에서 거의 흔들리지 않음(AGC가 계속 보정하고 있기 때문)
thickness = [2.30, 2.31, 2.29, 2.30, 2.30, 2.31, 2.29, 2.30, 2.30, 2.31, 2.29, 2.30,
             2.30, 2.29, 2.31, 2.30, 2.30, 2.29, 2.31, 2.30]

df = pd.DataFrame({
    "pass_no": pass_no,
    "출측두께_mm": thickness,
    "롤갭보정폭_mm": gap_comp,
    "압연하중_ton": load,
    "주모터전류_A": current,
})
print(df)

# STEP 2. 제어 대상(두께)과 조작량·부하·설비 상태(갭·하중·전류)의 변동성 비교
# - 표준편차가 클수록 패스가 진행되며 값이 많이 움직였다는 뜻
summary = df.drop(columns="pass_no").agg(["mean", "std"]).round(3)
print(summary)

# STEP 3. pass_no와의 상관계수 - "패스가 진행될수록 이 값이 꾸준히 커지는가?"
corr_with_pass = df.drop(columns="pass_no").corrwith(df["pass_no"]).round(3)
print(corr_with_pass)

# STEP 4. 롤 교체 시점 자동 탐지 - 압연 하중이 전 패스 대비 크게 떨어진 지점을 찾기
load_diff = df["압연하중_ton"].diff()
replace_pass = df.loc[load_diff < -30, "pass_no"]
print(replace_pass.tolist())

# STEP 5. 교체 이력을 반영해 캠페인을 두 구간으로 나눠 다시 확인
df["campaign"] = ["1차 캠페인" if p < replace_pass.iloc[0] else "2차 캠페인" for p in df["pass_no"]]
campaign_corr = df.groupby("campaign").apply(
    lambda g: g["pass_no"].corr(g["압연하중_ton"]), include_groups=False
).round(3)
print(campaign_corr)

# 결과 해석
# - 표준편차: 출측두께 0.007mm로 사실상 흔들림이 없는 수준인 반면, 압연하중 20.0ton·
#   주모터전류 10.6A·롤갭보정폭 0.020mm는 훨씬 크게 움직임 - "제어 대상"만 유독 조용함
# - 캠페인 전체 기준 pass_no 상관계수: 출측두께 -0.012(거의 0)로 안정적 유지, 반면 하중·
#   갭보정폭은 0.195, 전류는 0.063으로 교체로 인한 급락 때문에 뚜렷한 추세가 가려져 보임
# - 그런데 교체 시점(13패스, STEP 4)을 기준으로 캠페인을 나눠서(STEP 5) 다시 보면 두 구간
#   모두 상관계수 1.0 - 각 캠페인 안에서는 패스가 진행될수록 하중이 완전히 일정한 비율로
#   증가하고 있었다는 뜻
# - 즉 "두께만 보면 계속 정상"처럼 보이지만, 그 두께를 지키기 위한 조작량·부하·설비 상태는
#   각 캠페인 안에서 꾸준히 우상향하고 있었음 - 이것이 AGC 뒤에 숨어 있던 롤 열화의 선행 신호
