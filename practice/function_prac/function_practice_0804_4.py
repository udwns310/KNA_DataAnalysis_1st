# =====================================================================
# [기본문제] 실습 4. 반환값으로 간단 계산기 만들기
# =====================================================================
def compute_average(a, b):
    return (a + b) / 2

result = compute_average(80, 90)
print(result)       # 85.0
print(result + 5)   # 90.0 (담은 값을 이어 씀)
