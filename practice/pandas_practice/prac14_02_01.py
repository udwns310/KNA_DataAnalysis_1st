import pandas as pd

df = pd.read_csv('data/14_hydraulic.csv', encoding='utf-8')

# 실습 1. 평균·분산·표준편차 구하기
# 전체와 라인별로 평균·분산·표준편차 구하기
# 대푯값(평균)과 흩어짐(분산·표준편차)을 나타내는 세 통계량 구하기

# · 진동 열 전체의 평균·분산·표준편차를 각각 구하기
print(df['진동'].mean().round(3))   # 0.616
print(df['진동'].var().round(3))    # 0.004
print(df['진동'].std().round(3))    # 0.064

# · 표준편차를 제곱하면 분산과 같아지는지 확인
print(0.064 * 0.064)  # 0.004096

# · 냉각기상태(라인 대신)로 그룹을 나눠 라인별 평균과 표준편차 비교
print(df.groupby('냉각기상태')['진동'].mean().round(3))
print(df.groupby('냉각기상태')['진동'].std().round(3))
# 한 번에 모아보기
print(df.groupby('냉각기상태')['진동'].agg(['mean', 'std']).round(3))
#         mean    std
# 냉각기상태
# 고장     0.688  0.048
# 저하     0.610  0.010
# 정상     0.549  0.009

# 판다스가 더 권장하는 방식으로 통계항목별 이름 붙여 정리하기
print(df.groupby('냉각기상태').agg(
    평균=('진동', 'mean'),
    표준편차=('진동', 'std')
).round(3))
#          평균    표준편차
# 냉각기상태
# 고장     0.688  0.048
# 저하     0.610  0.010
# 정상     0.549  0.009

