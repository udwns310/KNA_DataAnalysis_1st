import pandas as pd

df = pd.read_csv('data/14_hydraulic.csv', encoding='utf-8')

# 실습 4. agg 진단표 만들기
# 이름 붙인 agg로 설비 진단표를 만들고 정렬
# 여러 통계를 담은 진단표를 만들고 정렬해 우선순위 파악

# · 밸브상태(설비 대신)로 그룹을 나눠 측정수·평균온도·온도편차·평균진동·평균압력을 이름 붙여 집계
report = df.groupby('밸브상태').agg(
    측정수=('온도', 'count'),
    평균온도=('온도', 'mean'),
    온도편차=('온도', 'std'),
    평균진동=('진동', 'mean'),
    평균압력=('압력', 'mean')
).round(2)

print(report)
#       측정수   평균온도  온도편차  평균진동    평균압력
# 밸브상태
# 경미     20  44.86  8.11  0.62  161.56
# 심각     19  46.02  8.40  0.63  163.39
# 정상     61  45.11  7.79  0.61  159.99
# 지연     20  45.86  8.93  0.62  161.27

# · 온도편차를 기준으로 내림차순 정렬
print(report.sort_values('온도편차', ascending=False))
#       측정수   평균온도  온도편차  평균진동    평균압력
# 밸브상태
# 지연     20  45.86  8.93  0.62  161.27
# 심각     19  46.02  8.40  0.63  163.39
# 경미     20  44.86  8.11  0.62  161.56
# 정상     61  45.11  7.79  0.61  159.99

print(report.sort_values('평균진동', ascending=False))
#       측정수   평균온도  온도편차  평균진동    평균압력
# 밸브상태
# 심각     19  46.02  8.40  0.63  163.39
# 경미     20  44.86  8.11  0.62  161.56
# 지연     20  45.86  8.93  0.62  161.27
# 정상     61  45.11  7.79  0.61  159.99

