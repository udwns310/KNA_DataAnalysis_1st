#    이상한 값도 정상으로 놓쳐버리기 쉬움. 그래서 2~3배 정도가 "너무 예민하지도, 너무
#    둔감하지도 않은" 실무적인 균형점으로 자주 쓰이는 것 - 실제로는 다루는 설비나
