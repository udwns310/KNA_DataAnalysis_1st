# [개념] 1차원과 2차원 배열
# - 1차원: 값이 한 줄로 늘어선 형태 - 센서 하나가 시간에 따라 측정한 값
# - 2차원: 행과 열을 가진 표 모양 - 가로줄이 행, 세로줄이 열
# - 설비 데이터를 본격 분석할 때는 대부분 2차원을 다루게 됨

# [정리] 차원이란 값을 늘어놓는 방향의 수
# - 1차원은 한 줄로 선 사람들처럼 앞뒤 순서만 있고,
# - 2차원은 극장 좌석처럼 몇 번째 줄 몇 번째 자리 두 정보로 위치가 정해짐
# - 온도·진동·압력 센서가 여러 시점에 측정하면, 행이 시점이고 열이 센서인 2차원 표가 됨
# - 1차원은 그 표의 한 줄을 떼어낸 것

# [개념] 배열의 차원(ndim) - ndim으로 배열이 몇 차원인지 확인, 괄호 없는 속성
a = np.array([1, 2, 3])
b = np.array([[1, 2], [3, 4]])
print(a.ndim)  # 1
print(b.ndim)  # 2
# ndim은 number of dimensions, 차원 개수 - 한 줄짜리는 1, 표 모양은 2

# [정리] 속성과 함수의 차이
# - 함수는 동작을 실행 - 괄호 있음 (예: np.array())
# - 속성은 정보를 꺼내봄 - 괄호 없음 (예: 배열.ndim)
# - 차원·형태·크기 같은 정보는 배열이 만들어질 때 이미 딸려 있어서, 새로 계산하는 게 아니라 들여다보는 것
# - 이 구분은 shape, size, dtype에도 똑같이 적용

# [개념] 배열의 형태(shape) - shape으로 행과 열 크기 확인, 앞=행 뒤=열
readings_2d = np.array([[1, 2, 3], [4, 5, 6]])
print(readings_2d.shape)  # (2, 3)
# 앞 숫자 2가 행, 뒤 숫자 3이 열 - 괄호로 묶여 나오는 건 결과가 튜플이기 때문

# [정리] shape 읽는 법 - 분석가가 데이터를 처음 만나면 가장 먼저 던지는 질문
# (5,): 값 5개인 1차원 배열 - 쉼표는 오타가 아니라 값 하나짜리 묶음이라는 표시
# (2, 3): 2행 3열 - 앞이 행, 뒤가 열
# (1000, 20): 시점 1000개, 센서 20개

# [개념] 배열의 크기(size) - size로 값의 전체 개수 확인, 행 × 열
print(readings_2d.size)  # 6
# shape은 "어떤 모양인가", size는 "값이 모두 몇 개인가" - size도 속성이라 괄호 없음

# [정리] shape과 size의 관계 - shape은 모양, size는 전체 개수
# shape의 숫자들을 곱하면 size - (500, 12)면 size는 6000
# 모양은 바꿀 수 있어도, 담긴 값의 총 개수(size)는 변하지 않음 - 이건 reshape에서 중요해짐

# [개념] 자료형(dtype) - dtype으로 값의 종류 확인, 정수 int 실수 float
int_arr = np.array([1, 2, 3])
float_arr = np.array([1.5, 2.7, 3.1])
print(int_arr.dtype)  # int64
print(float_arr.dtype)  # float64
# 뒤의 64는 저장 공간 크기

# [정리] dtype을 꼭 확인해야 하는 이유 - 데이터를 불러온 직후 dtype 확인이 계산 오류를 막아줌
# - 정수 int: 소수점 없는 값 - 측정 순번, 설비 번호
# - 실수 float: 소수점 있는 값 - 온도, 진동
# - 숨은 글자: 숫자처럼 보여도 글자로 저장되어 있을 수 있음 - 계산 시 오류 발생


print("\n===================== 실습 4. 배열 구조 확인하기 =====================")
# 목표: 표 모양 배열의 차원·형태·개수를 속성으로 확인
# 단계: ① 설비별 측정값을 담은 이차원 배열 준비 -> ② ndim으로 차원, shape으로 형태, size로 전체 개수 확인
#      -> ③ 세 속성값 출력
# 예상 결과: 차원 2, 형태 (2, 3), 개수 6 출력
