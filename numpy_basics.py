# [개념] np.arange로 연속 정수 만들기 - 일정 간격의 연속된 숫자를 자동으로 생성
print(np.arange(5))  # [0 1 2 3 4]
print(np.arange(0, 10, 2))  # [0 2 4 6 8]
# np.arange(5)는 0부터 4까지 - 핵심은 끝 숫자 5가 제외된다는 점
# 세 번째 값 2는 간격 - 0부터 2씩 건너뜀

# [정리] np.arange의 핵심 규칙 - 끝 숫자는 포함되지 않음, "시작 포함, 끝 제외"
# - 가장 자주 하는 실수: arange(5)를 0부터 5까지 여섯 개라고 착각 (실제로는 0부터 4까지 다섯 개)
# - np.arange만의 규칙이 아니라 파이썬 전체의 약속 - 곧 배울 슬라이싱에서도 똑같이 끝이 제외됨
# - 소수점 간격은 미세한 오차가 생길 수 있으니 정확히 나눌 땐 linspace 사용

# [강사님께 질문하기] "시작 포함, 끝 제외" 규칙이 개수 세기에 편하다는 건 알겠는데,
# 이 규칙 때문에 실제로 더 편해지는 다른 상황도 있나요?
# -> 답변: 있음. 이 규칙 덕분에 배열을 아무 지점에서나 둘로 나눠도 겹치거나 빠지는
#    부분 없이 정확히 이어붙일 수 있음. 예를 들어 배열을 k번째 지점에서 arr[:k]와
#    arr[k:]로 나누면, 앞부분은 k번을 포함하지 않고 뒷부분은 k번부터 시작하니 두
#    조각을 다시 이어붙이면 k가 몇이든 항상 정확히 원래 배열이 됨. 만약 끝을 포함하는
#    규칙이었다면 나누는 지점의 값이 앞뒤 양쪽에 겹쳐 들어가거나 뭔가 조정을 해줘야
#    정확히 나뉨 - "끝 제외"는 데이터를 이어붙이거나 잘라 쓰는 코드를 훨씬 단순하게
#    만들어주는 규칙인 것

# [개념] np.linspace로 균등 분할하기 - 시작과 끝 사이를 정해진 개수로 똑같이 분할
print(np.linspace(0, 1, 5))  # [0.   0.25 0.5  0.75 1.  ]
# 세 번째 값 5는 간격이 아니라 만들 점의 개수 - arange는 간격을 정하지만 linspace는 개수를 정함
# 출력의 끝값 1이 포함됨 (arange는 끝값 제외, linspace는 끝값 포함)

# [정리] arange와 linspace - 무엇을 정하나
# arange: 간격을 정함 / 개수는 계산해야 앎 / 끝값 제외
# linspace: 개수를 정함 / 간격은 자동 계산 / 끝값 포함
# 그래프 축을 만들 때는 보통 개수를 정하니 linspace를 자주 씀

# [개념] zeros·ones·full 초기화 배열 - 같은 값으로 가득 찬 배열을 한 번에 생성
print(np.zeros(3))  # [0. 0. 0.] - 0.은 실수 배열이라는 표시
