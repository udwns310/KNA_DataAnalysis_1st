# [개념] reshape로 형태 바꾸기 - 값은 그대로, 모양만 바꾸기, 값 개수는 같아야 함
sequence = np.arange(12)
print(sequence.reshape(3, 4))  # 3행 4열 배열 (0~11)
print(sequence.reshape(-1, 2))  # 6행 2열 (행은 자동 계산)
# 값 12개짜리를 3행 4열로 바꿈 - 값은 그대로고 모양만 변함, -1을 쓰면 NumPy가 나머지 크기를 자동 계산

# [정리] reshape의 규칙
# - 바꾸기 전후 값 개수가 같아야 함 - 12개를 3행 5열로는 불가 (15칸이라 안 됨, cannot reshape 오류는 거의 이 문제)
# - 행이나 열에 -1을 넣으면 나머지를 자동 계산 - 열만 정하고 행은 -1로 두면 NumPy가 맞춤
# - 단, -1은 행과 열 중 한 곳에만 쓸 수 있음

# [강사님께 질문하기] reshape에서 -1을 쓰면 왜 하필 행에도 열에도 다 쓸 수 없고
# 한 곳에만 써야 하나요?
# -> 답변: -1은 "나머지는 네가 알아서 계산해"라는 뜻인데, 행과 열 둘 다 -1이면 컴퓨터
#    입장에서는 "둘 다 모르는 값"이 되어버려서 계산할 방법이 없음. 마치 "가로 곱하기
#    세로가 12인데, 가로도 모르고 세로도 모른다"고 하면 답이 무한히 많아지는 것과 같음.
#    한쪽만 -1로 두면 다른 쪽 숫자가 이미 정해져 있으니, 전체 값 개수를 그 숫자로
#    나누기만 하면 나머지 쪽이 딱 하나로 정해짐

# [개념] flatten으로 1차원 만들기 - 표 모양을 한 줄로 펴기, 위 행부터 왼쪽에서 오른쪽으로
table = np.array([[1, 2, 3], [4, 5, 6]])
print(table.flatten())  # [1 2 3 4 5 6]
# reshape이 한 줄을 표로 만든다면, flatten은 반대로 표를 한 줄로 폄 (책 읽는 방향)

# [정리] flatten의 특징
# - 위 행부터 왼쪽에서 오른쪽 순서로 폄 (책 읽는 방향)
# - 표 전체에서 통계 낼 때, 전체를 한꺼번에 다룰 때 유용 (센서 구분 없이 전체 평균 구하기 등)
# - flatten도 원본을 바꾸지 않고 새 배열을 만듦

# [정리] 형태 변환 정리
# 함수      | 하는 일   | 결과
# reshape   | 모양 바꾸기 | 원하는 행·열
# flatten   | 한 줄로 펴기 | 1차원 배열
# 공통점: 값 자체는 바꾸지 않고 배치만 바꾸며, 값의 총 개수는 변하지 않음
# 둘 다 결과를 새 이름에 담아야 쓸 수 있음

