# [문제 상황] 파이썬 리스트의 한계 - 리스트는 숫자에 곱셈하면 계산이 아니라 반복이 일어남
temps_list = [70.5, 69.8, 73.7]
print(temps_list * 2)  # [70.5, 69.8, 73.7, 70.5, 69.8, 73.7] - 곱셈이 아니라 반복!
# 모든 값에 진짜로 곱셈을 하려면 반복문이 필요함
