# [정리] 분산의 의미와 한계
# - 의미: 작으면 안정, 크면 불안정 - 고장 징후가 있으면 값이 요동쳐 분산이 커짐
# - 한계: 값을 제곱해 구하므로 단위가 달라짐 (rpm의 분산은 "rpm의 제곱"이라는 어색한 단위)

