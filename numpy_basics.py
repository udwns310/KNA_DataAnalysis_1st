# - 약점: 유난히 크거나 작은 값(이상치)에 휘둘림 - 모든 값을 더해서 계산하니 그대로 반영됨
# - 사례: 대부분 1180~1250인데 50 하나로 평균이 980까지 끌려 내려감 - 평균만으론 잘못된 그림

# [개념] 중앙값(median) - 값을 줄 세웠을 때 한가운데 오는 값, np.median 형태
print(np.median(rotation_sample))  # 1200.0 - 대부분 값에 가까움
print(rotation_sample.mean())  # 980.0 - 이상치에 끌려간 평균과 대비됨

# [정리] 중앙값의 강점 - 두 통계를 함께 구해 비교하는 습관(데이터 건강 점검)
# - 강점: 이상치에 흔들리지 않음 - 맨 끝 값이 50이든 -500이든 한가운데 위치는 그대로
