# Q1. 없는 키를 대괄호[]로 꺼내는 것과 get()으로 꺼내는 것은 뭐가 다른가요?
# -> A. 대괄호는 없는 키를 만나면 바로 KeyError를 내며 프로그램이 멈추지만,
#       get()은 오류 없이 None(또는 지정한 기본값)을 돌려주고 계속 진행됨
sensors = {"모터온도": 78}
