# print(sensors["압력"])       # KeyError: '압력' (실행하면 여기서 멈춤)

# Q2. update()로 딕셔너리를 갱신하면, 갱신된 새 딕셔너리를 결과로 돌려주나요?
# -> A. 아니요. update()는 원본 딕셔너리 "자체"를 직접 고칠 뿐 반환값은 없음(None)
#       리스트의 append/extend/sort와 똑같은 성격 - "바꾸는 메서드"는 새 값을 돌려주지 않음
info = {"모터온도": 78}
result = info.update({"압력": 95})
print(result)  # None (update의 반환값)
print(info)  # {'모터온도': 78, '압력': 95} (원본이 이미 바뀌어 있음)

# Q3. 딕셔너리의 in은 값이 아니라 키만 본다고 했는데, 값도 있는지 확인하려면 어떻게 하나요?
# -> A. values()로 값 묶음만 따로 꺼낸 뒤 그 안에서 in을 쓰면 됨
sensors = {"모터온도": 78, "압력": 95}
print(78 in sensors)  # False (키 기준이라 없음 취급)
print(78 in sensors.values())  # True (값 묶음 안에서는 찾아짐)

# Q4. zip으로 이름 리스트와 값 리스트를 짝지을 때, 두 리스트의 길이가 다르면
#     오류가 나서 바로 알아챌 수 있나요?
# -> A. 아니요, 오류 없이 조용히 더 짧은 쪽 길이에 맞춰서 딱 거기까지만 짝지어짐.
#       긴 쪽에 남는 값들은 아무 신호 없이 그냥 버려짐 - 두 리스트 길이가 같은지
#       미리 확인하는 습관이 필요함
short_names = ["온도", "압력", "진동"]
short_values = [78, 95]  # 값이 하나 모자람
print(dict(zip(short_names, short_values)))  # {'온도': 78, '압력': 95}  ('진동'은 조용히 사라짐)

