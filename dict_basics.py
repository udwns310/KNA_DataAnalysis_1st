# =====================================================================
# 딕셔너리 (Dictionary) - 이름으로 값을 찾는 자료구조
# =====================================================================

# [문제 상황] 위치로만 값을 관리할 때의 불편함
# - 리스트는 번호(인덱스)로 값을 찾음 - 센서가 20개면 몇 번이 무슨 센서인지 다 외워야 함
# - 센서 하나가 빠지면 그 뒤 번호가 전부 한 칸씩 밀려서 외워둔 위치가 다 어긋남
# - 위치가 아니라 "이름"으로 바로 찾는 도구가 필요 -> 딕셔너리

# [개념] 딕셔너리 - 이름표(키)로 값을 찾는 자료구조
# - 단어를 찾으면 뜻이 나오는 사전처럼, 이름표(키)를 찾으면 그 값이 바로 나옴
# - 순서 번호 대신 이름으로 찾으므로 위치가 바뀌어도 문제없음
# - 키와 값이 항상 짝을 이뤄 저장됨 (key : value)

# [개념] 딕셔너리 만들기 - 중괄호 안에 키:값을 콤마로 나열
sensors = {"모터온도": 78, "진동": 0.5}
print(sensors)  # {'모터온도': 78, '진동': 0.5}
print(type(sensors))  # <class 'dict'>

empty = {}  # 빈 딕셔너리
print(type(empty))  # <class 'dict'>

# [정리] 빈 중괄호 {} 는 딕셔너리 - 콜론(:)이 있으면 딕셔너리, 콜론 없이 값만 있으면 셋
# (빈 셋은 {} 로 못 만들고 set() 함수로 따로 만들어야 함)

# [개념] 키로 값 꺼내기 - 대괄호 안에 키를 넣어 연결된 값을 바로 꺼냄
print(sensors["모터온도"])  # 78
print(sensors["진동"])  # 0.5

# [주의] 없는 키를 대괄호로 꺼내면 KeyError 발생 (안전한 조회는 뒤에서 배울 get으로)
# print(sensors["압력"])  # KeyError: '압력'

# [개념] 새로운 키-값 추가하기 - 없는 키에 값을 대입하면 그 쌍이 새로 추가됨
sensors["압력"] = 95
print(sensors)  # {'모터온도': 78, '진동': 0.5, '압력': 95}

# [개념] 기존 값 수정하기 - 있는 키에 값을 대입하면 그 값만 덮어씀 (추가와 문법이 동일)
sensors["모터온도"] = 80
print(sensors)  # {'모터온도': 80, '진동': 0.5, '압력': 95}

# [개념] del로 키-값 쌍 삭제하기
del sensors["진동"]
print(sensors)  # {'모터온도': 80, '압력': 95}

# [정리] 딕셔너리 기본 동작 정리
# 동작 | 문법                  | 비고
# 조회 | 딕셔너리[키]          | 없으면 KeyError
# 추가 | 딕셔너리[새 키] = 값   | 추가·수정 문법이 동일
# 수정 | 딕셔너리[있는 키] = 값 | 값만 덮어씀
# 삭제 | del 딕셔너리[키]      | 없는 키를 지우면 오류


print("\n===================== 실습 1. 딕셔너리 만들고 다루기 =====================")
# 목표: 센서명을 키, 측정값을 값으로 하는 딕셔너리를 만들고 추가·수정·안전 조회하기
# 단계: ① 센서명을 키, 측정값을 값으로 딕셔너리 저장 -> ② 키로 값을 꺼내고 새 키로 추가·기존 키로 수정
#      -> ③ get으로 없는 키를 기본값으로 조회, in으로 키 존재 확인
# 예상 결과: 78 / 추가·수정된 딕셔너리 / 0 (없는 키) / True
readings = {"온도": 78, "진동": 0.5}
print(readings["온도"])  # 78
readings["압력"] = 95  # 새 키 추가
readings["온도"] = 80  # 기존 키 수정
print(readings)  # {'온도': 80, '진동': 0.5, '압력': 95}
print(readings.get("유량", 0))  # 0
print("온도" in readings)  # True


# =====================================================================
# get·in - 오류 없이 안전하게 키 다루기
# =====================================================================

# [개념] get - 없는 키를 꺼내도 오류 대신 기본값을 돌려줌
sensors = {"모터온도": 78}
print(sensors.get("모터온도"))  # 78
print(sensors.get("유량"))  # None (기본값을 안 정하면 None)
print(sensors.get("유량", 0))  # 0 (두 번째 인자로 기본값 지정)

# [개념] in - 특정 키가 딕셔너리에 있는지 참·거짓으로 확인
sensors = {"모터온도": 78, "펌프압력": 95}
print("모터온도" in sensors)  # True (키를 확인)
print(78 in sensors)  # False (값이 아니라 키를 봄!)

# [주의] 딕셔너리의 in은 항상 "키"만 봄 - 값을 넣으면 있어도 False가 나옴
if "유량" in sensors:
    print(sensors.get("유량"))
else:
    print("유량 없음")  # 유량 없음

# [강사님께 질문하기] 리스트의 in은 리스트 안 값을 하나하나 비교하면서 찾는다고 배웠는데,
# 딕셔너리도 in을 쓸 때 안에 있는 키들을 처음부터 하나하나 다 비교하면서 찾는 거예요?
# -> 답변: 아니요. 딕셔너리는 리스트처럼 앞에서부터 순서대로 하나씩 훑지 않음. 키 하나만
#    주면 그 키가 있어야 할 자리로 바로 찾아가는 방식이라, 딕셔너리 안에 값이 아무리
#    많아도 찾는 데 걸리는 시간이 거의 그대로임. 그래서 딕셔너리가 "이름으로 빠르게
#    찾는" 자료구조라고 하는 것 - 이름표 수가 늘어나도 찾는 속도는 거의 안 느려짐


# =====================================================================
# 딕셔너리 키가 될 수 있는 것
# =====================================================================

# [개념] 딕셔너리 키가 될 수 있는 것 - 바뀌지 않는 값만 키가 될 수 있음
# 자료형 | 키 가능 | 이유
# 문자열 | 가능    | 한 번 정해지면 안 바뀜
# 숫자   | 가능    | 정수·실수 모두 안 바뀜
# 튜플   | 가능    | 튜플도 안 바뀜
# 리스트 | 불가    | 리스트는 언제든 값이 바뀔 수 있어서 키로 못 씀

location = {(0, 0): "출발점"}  # 튜플은 키로 사용 가능
print(location[(0, 0)])  # 출발점

# wrong = {[0, 0]: "출발점"}  # TypeError: unhashable type: 'list'

# [강사님께 질문하기] 딕셔너리 키는 왜 하필 "바뀌지 않는 값"만 가능한 거예요?
# 그냥 키를 하나하나 비교해서 찾아도 되지 않나요?
# -> 답변: 딕셔너리는 키를 하나하나 비교하면서 찾는 방식이 아니라, 키 값을 이용해서
#    미리 계산해둔 자리로 바로 찾아가는 방식으로 빠르게 동작함. 그런데 나중에 그 키의
#    내용이 바뀌어 버리면, 원래 계산해서 정해뒀던 자리와 어긋나 버려서 다시는 그 값을
#    못 찾게 됨 - 사물함에 이름표를 붙여놨는데 이름표 내용이 슬쩍 바뀌면 내 물건이 어느
#    사물함인지 못 찾게 되는 것과 같은 상황. 그래서 한 번 정해지면 안 바뀌는 값만
#    키로 쓸 수 있게 만들어져 있음


# =====================================================================
# 순회 - keys, values, items
# =====================================================================

# [개념] keys()·values() - 키만, 값만 따로 꺼내기
sensors = {"모터온도": 78, "압력": 95}
print(list(sensors.keys()))  # ['모터온도', '압력']
print(list(sensors.values()))  # [78, 95]

avg = sum(sensors.values()) / len(sensors)
print(avg)  # 86.5

# [강사님께 질문하기] keys()로 꺼낸 이름들의 순서가 처음에 딕셔너리에 넣은 순서랑
# 같은 건가요, 아니면 매번 뒤죽박죽 섞여서 나오는 건가요?
# -> 답변: 지금 파이썬에서는 넣은 순서 그대로 유지됨. keys()·values()·items() 모두
#    딕셔너리에 저장된 순서(=넣은 순서) 그대로 꺼내줌. 다만 그렇다고 딕셔너리를
#    "순서"가 중요한 용도로 쓰면 안 됨 - 딕셔너리는 어디까지나 "이름으로 찾기" 용도이고,
#    순서 자체가 중요한 데이터라면 리스트가 더 적합한 선택

# [개념] items() - 키와 값을 튜플로 묶어 함께 꺼냄 (반복문에서 가장 많이 쓰는 패턴)
for name, value in sensors.items():
    print(name, "측정값:", value)

# [개념] len() - 담긴 키-값 쌍의 개수
print(len(sensors))  # 2

# [정리] 순회 세 가지 방법
# 방법   | 꺼내는 것 | 쓰는 경우
# keys   | 키만      | 이름 목록 확인
# values | 값만      | 합계·평균 계산
# items  | 키와 값   | 이름과 값을 함께 다룰 때 (실무에서 가장 흔함)


print("\n===================== 실습 3. 딕셔너리로 통계 내기 =====================")
# 목표: values로 평균을, items 순회로 최댓값 센서를 구하기
# 단계: ① 센서명-측정값 딕셔너리 저장 -> ② values의 합을 개수로 나눠 평균 구하기
#      -> ③ items로 순회하며 가장 큰 값과 그 센서명을 찾아 출력
# 예상 결과: 평균: 76.7 / 최댓값 센서: 압력 95
sensor_values = {"온도": 78, "압력": 95, "진동": 57}
sensor_avg = sum(sensor_values.values()) / len(sensor_values)
print(f"평균: {sensor_avg:.1f}")  # 평균: 76.7

top_name = None
top_value = None
for name, value in sensor_values.items():
    if top_value is None or value > top_value:
        top_name = name
        top_value = value
print("최댓값 센서:", top_name, top_value)  # 최댓값 센서: 압력 95


# =====================================================================
# 임계값 비교 - items 순회 + 조건문
# =====================================================================

# [개념] 순회하며 임계값과 비교하기 - 측정값과 임계값을 각각 딕셔너리로 관리하고
#        같은 센서 이름을 다리 삼아 두 딕셔너리를 연결
values = {"모터온도": 95, "압력": 88}
limits = {"모터온도": 90, "압력": 90}
for name, value in values.items():
    if value > limits[name]:
        print(name, "경고")  # 모터온도 경고


print("\n===================== 실습 5. 임계값으로 경고 센서 분류하기 =====================")
# 목표: 측정값과 임계값 딕셔너리를 비교해 경고 센서를 모으기
# 단계: ① 측정값 딕셔너리와 임계값 딕셔너리를 각각 저장 -> ② items로 순회하며 각 센서 값이 같은 이름의 임계값을 넘는지 비교
#      -> ③ 넘는 센서 이름을 빈 리스트에 모아 출력
# 예상 결과: 경고 센서: ['온도']
current_readings = {"온도": 95, "압력": 88}
threshold_limits = {"온도": 90, "압력": 90}
warning_sensors = []
for name, value in current_readings.items():
    if value > threshold_limits[name]:
        warning_sensors.append(name)
print("경고 센서:", warning_sensors)  # 경고 센서: ['온도']


# =====================================================================
# update - 여러 값 한 번에 갱신
# =====================================================================

# [개념] update - 새 딕셔너리를 넘기면 있는 키는 갱신, 없는 키는 추가 (한 번에 처리)
sensors = {"모터온도": 78, "진동": 0.5}
new_data = {"모터온도": 80, "유량": 42}
sensors.update(new_data)
print(sensors)  # {'모터온도': 80, '진동': 0.5, '유량': 42}


print("\n===================== 실습 2. update로 여러 값 한 번에 갱신하기 =====================")
# 목표: update로 여러 항목을 한 번에 갱신하고 삭제·개수 확인하기
# 단계: ① 센서 딕셔너리와 새 데이터 딕셔너리를 각각 저장 -> ② update로 새 데이터를 한 번에 반영(있으면 수정, 없으면 추가)
#      -> ③ del로 특정 키를 삭제하고 len으로 개수 확인
# 예상 결과: 갱신된 딕셔너리 / 센서 수: 2
station_data = {"온도": 78, "진동": 0.5}
new_readings = {"온도": 82, "압력": 95}
station_data.update(new_readings)
print(station_data)  # {'온도': 82, '진동': 0.5, '압력': 95}
del station_data["진동"]
print("센서 수:", len(station_data))  # 센서 수: 2


# =====================================================================
# zip - 두 리스트를 딕셔너리로 만들기
# =====================================================================

# [개념] zip - 이름 리스트와 값 리스트를 지퍼처럼 앞에서부터 하나씩 짝지어 dict()로 묶음
names = ["모터온도", "진동", "압력"]
readings_list = [78, 0.5, 95]
sensors = dict(zip(names, readings_list))
print(sensors)  # {'모터온도': 78, '진동': 0.5, '압력': 95}

# [강사님께 질문하기] zip으로 딕셔너리를 만들 때, 이름 리스트에 같은 이름이 두 번
# 들어있으면 어떻게 되나요? 값이 두 개 다 저장되나요, 아니면 하나만 남나요?
# -> 답변: 하나만 남음. 딕셔너리는 같은 키를 두 번 가질 수 없어서, 같은 이름이 여러 번
#    나오면 나중에 짝지어진 값이 앞의 값을 덮어써 버림. 즉 이름이 겹치면 먼저 들어온
#    값은 조용히 사라지고 마지막 값만 남게 됨 - 이름 리스트에 중복이 없는지 미리
#    확인하는 습관이 필요함


print("\n===================== 실습 4. zip으로 센서명-값 매핑하기 =====================")
# 목표: zip으로 두 리스트를 짝지어 딕셔너리로 만들기
# 단계: ① 센서명 리스트와 측정값 리스트를 각각 저장 -> ② zip으로 두 리스트를 짝지어 dict로 변환
#      -> ③ items로 순회하며 이름-값 쌍 출력
# 예상 결과: {'온도': 78, '진동': 0.5, '압력': 95} / 각 이름-값 쌍 출력
sensor_names = ["온도", "진동", "압력"]
sensor_readings = [78, 0.5, 95]
station_map = dict(zip(sensor_names, sensor_readings))
print(station_map)  # {'온도': 78, '진동': 0.5, '압력': 95}
for name, value in station_map.items():
    print(name, value)


# =====================================================================
# 딕셔너리 값에 리스트·튜플 담기, 그리고 구조 설계
# =====================================================================

# [개념] 값에 리스트 담기 - 센서 하나에 여러 측정값(이력)을 리스트로 매달기
sensors = {"모터온도": [78, 79, 80]}
temps = sensors["모터온도"]
print(sum(temps) / len(temps))  # 79.0
print(max(temps))  # 80

# [개념] 설비별 데이터 구조 설계 - 여러 정보를 담을 땐 무엇을 키로, 무엇을 값으로
#        할지 먼저 설계 (자주 찾는 정보를 키로 삼기)
motor = {
    "name": "1번 모터",
    "온도": [78, 79, 80],
    "status": "가동중",
}
print(motor["status"])  # 가동중


# =====================================================================
# 중첩 딕셔너리 - 딕셔너리 안에 딕셔너리
# =====================================================================

# [개념] 딕셔너리 안의 딕셔너리 - 설비 이름을 키, 설비 정보를 값으로 하는 큰 딕셔너리
# - 안쪽 값을 꺼낼 땐 키를 두 번 사용 (plant[설비][센서])
plant = {
    "1번모터": {"온도": 78, "상태": "정상"},
    "2번펌프": {"압력": 95, "상태": "경고"},
}
print(plant["2번펌프"]["압력"])  # 95


print("\n===================== 실습 6. 중첩 딕셔너리로 설비 관리하기 =====================")
# 목표: 딕셔너리 안에 딕셔너리를 담고 중첩 키로 접근·조건 검색하기
# 단계: ① 설비명을 키로, 각 설비 정보(딕셔너리)를 값으로 하는 중첩 딕셔너리 저장 -> ② 중첩 키로 특정 설비의 특정 값을 꺼내기
#      -> ③ items 순회로 상태가 "경고"인 설비만 찾아 출력
# 예상 결과: 95 / 2번펌프 점검 필요
equipment = {
    "1번모터": {"온도": 78, "상태": "정상"},
    "2번펌프": {"압력": 95, "상태": "경고"},
}
print(equipment["2번펌프"]["압력"])  # 95
for name, info in equipment.items():
    if info["상태"] == "경고":
        print(name, "점검 필요")  # 2번펌프 점검 필요


print("\n===================== 실습 7. 표 데이터를 딕셔너리로 변환하기 =====================")
# 목표: 행 문자열을 split으로 나눠 딕셔너리로 만들기
# 단계: ① 한 줄에 "센서명,측정값" 형태인 행 문자열들을 리스트로 저장 -> ② for로 각 행을 쉼표로 split해 이름과 값으로 나누기
#      -> ③ 이름을 키, 값을 숫자로 바꿔 딕셔너리에 추가
# 예상 결과: {'온도': 78.0, '압력': 95.0, '진동': 0.5}
raw_rows = ["온도,78", "압력,95", "진동,0.5"]
table = {}
for row in raw_rows:
    name, value = row.split(",")
    table[name] = float(value)
print(table)  # {'온도': 78.0, '압력': 95.0, '진동': 0.5}


print("\n===================== 실습 8. 센서 데이터 통합 정리 =====================")
# 목표: 딕셔너리로 평균을 구하고 위험 센서를 셋으로 모아 정렬 출력하기
# 단계: ① 센서 측정값 딕셔너리와 임계값 딕셔너리 저장 -> ② values로 전체 평균 구하기
#      -> ③ items 순회로 임계값 초과 센서를 셋에 모으기 -> ④ 셋을 정렬해 출력
# 예상 결과: 평균: 95.5 / 위험 센서: ['압력', '온도']
final_readings = {"온도": 96, "압력": 98, "진동": 92.5}
final_limits = {"온도": 90, "압력": 90, "진동": 95}
final_avg = sum(final_readings.values()) / len(final_readings)
print(f"평균: {final_avg:.1f}")  # 평균: 95.5

risky_sensors = set()
for name, value in final_readings.items():
    if value > final_limits[name]:
        risky_sensors.add(name)
print("위험 센서:", sorted(risky_sensors))  # 위험 센서: ['압력', '온도']


