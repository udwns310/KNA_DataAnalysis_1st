print(
    "\n===================== 실습 9. 두 리스트의 차이를 계산해 걸러내고 최댓값까지 구하기 ====================="
)
# 목표: 목표 온도와 실제 온도 두 리스트를 동시에 돌며 차이를 계산하고, 차이가 큰 것만 골라
#      리스트에 담은 뒤 그중 최댓값(가장 크게 벗어난 차이)까지 이어서 구하기
# 단계: ① 목표·실제 온도 리스트를 준비 -> ② range(len())으로 같은 i의 실제-목표 차이를 계산
#      -> ③ 차이가 5 초과인 값만 diffs 에 append -> ④ diffs 를 다시 for 로 돌며 최댓값을 찾아 출력
# 예상 결과: 벗어난 차이: [7, 8] / 가장 크게 벗어난 차이: 8
target_temps = [25, 30, 28, 32, 27]
actual_temps = [26, 37, 29, 40, 28]
diffs = []
for i in range(len(target_temps)):
    diff = actual_temps[i] - target_temps[i]
    if diff > 5:
        diffs.append(diff)
print("벗어난 차이:", diffs)

biggest_diff = diffs[0]
for d in diffs:
    if d > biggest_diff:
        biggest_diff = d
print("가장 크게 벗어난 차이:", biggest_diff)


print(
    "\n===================== 실습 10. 조건 하나로 두 리스트에 동시에 분류하기 ====================="
)
# 목표: if-else 하나로 조건을 만족하는 값과 안 하는 값을 각각 다른 리스트로 동시에 분류하고,
#      두 리스트 길이의 합이 원본 개수와 같은지 검증해 값이 하나도 안 빠졌는지 확인
# 단계: ① 점수 리스트를 준비하고 합격·불합격 빈 리스트를 반복 밖에서 만들기 -> ② for-if-else 로
#      60 이상이면 합격, 아니면 불합격에 append -> ③ 두 리스트를 각각 출력 -> ④ 두 리스트
#      길이의 합이 원본 리스트 길이와 같은지 비교해 True/False 로 확인
# 예상 결과: 합격: [72, 88, 65] / 불합격: [50, 45] / 개수 일치: True
scores = [72, 50, 88, 45, 65]
pass_list = []
fail_list = []
for s in scores:
    if s >= 60:
        pass_list.append(s)
    else:
        fail_list.append(s)
print("합격:", pass_list)
print("불합격:", fail_list)
print("개수 일치:", len(pass_list) + len(fail_list) == len(scores))
