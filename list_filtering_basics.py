# 단계: ① 온도 리스트를 저장하고 합계·개수를 반복 밖에서 0으로 준비
#      -> ② for 안에서 if 로 30 초과인지 검사 -> ③ 조건에 맞는 값만 합계에 더하고 개수를 1 늘리기
