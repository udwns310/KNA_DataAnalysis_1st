#    리스트는 나중에 값이 더 들어올 걸 어느 정도 미리 대비해서 여유 자리를 마련해두는
#    식으로 관리되기 때문에, append할 때마다 매번 전체를 새로 옮기지 않아도 됨. 아주
#    가끔 그 여유 자리가 다 차는 순간에만 통째로 더 큰 자리로 옮기는 작업이 한 번씩
#    일어나지만, 평균적으로 보면 append 하나는 리스트 크기와 상관없이 거의 일정한 속도임

