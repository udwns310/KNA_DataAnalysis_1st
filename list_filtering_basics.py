# [정리] 반복문과 조건문 결합 구조 - 들여쓰기 단계가 실행 영역을 결정
# 들여쓰기 단계 | 실행 시점      | 실행 빈도
# 0단계(없음)   | for 문 자체    | 전체 흐름 중 1회
# 1단계         | 매 바퀴 실행   | 리스트 원소 수만큼
# 2단계(if 안)  | 조건 참일 때만 | 0회 ~ 원소 수만큼
temperatures = [25, 32, 28]
for temp in temperatures:  # 0단계: 전체 흐름 중 1회 시작
    print("검사 중")  # 1단계: 매 바퀴 실행 (3번)
    if temp >= 30:  # 1단계: 매 바퀴 검사 (3번)
        print("고온")  # 2단계: 조건 참일 때만 (1번)
print("검사 끝")  # 0단계 밖: 반복이 모두 끝난 뒤 정확히 1회

# [개념] 조건에 맞는 값만 골라내기 - 숫자 비교 등 다양한 조건으로 필터링 (if·elif 사용 가능)
