# 1) f-string 중괄호 안에서는 메서드 호출도 바로 가능 (변수 이름 자리에 식이 와도 됨)
raw_name = "  hong gil dong  "
print(f"이름: {raw_name.strip().title()}")  # 이름: Hong Gil Dong

# 2) 중괄호 자체를 문장에 출력하고 싶다면 두 번 겹쳐서 {{ }} 로 표시
print(f"딕셔너리 형태 예시: {{'key': 'value'}}")  # {'key': 'value'}

# 3) f-string은 큰따옴표(f"...")·작은따옴표(f'...') 둘 다 가능하지만
#    문장 안에 같은 따옴표를 쓰고 싶으면 바깥은 다른 종류의 따옴표로 감싸야 함
quote = f'그가 "안녕하세요"라고 말했다'
print(quote)
