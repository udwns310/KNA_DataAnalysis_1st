# [문제 상황] 결과를 보기 좋게 출력하고 싶다
# - 숫자·글자를 섞은 문장을 + 로 연결하면 번거로움
# - 따옴표·더하기 남발, 숫자마다 str()로 감싸야 함
# - 완성 문장이 코드만 봐선 한눈에 안 들어옴
# -> 이 불편을 푸는 도구가 f-string

name = "PUMP_A"
temp = 36

# 방법1) + 연결 방식 (번거로움, 숫자는 str() 형변환 필수)
print("설비 " + name + "의 현재 온도는 " + str(temp) + "도 입니다.")

# 방법2) f-string 방식 (짧고 안전)
print(f"설비 {name}의 현재 온도는 {temp}도 입니다.")


# [개념] f-string이란
# - 문자열 안에 변수 값을 바로 끼워 넣는 출력 방법
# - 따옴표 앞에 f, 변수 자리는 중괄호 {변수}
# - f'설비 {code} 점검' -> '설비 EQP-001 점검'
# - 완성될 문장을 그대로 쓰고 변수만 중괄호로 표시하면 됨

# [기본 문법] f"...{변수}..."
# - 따옴표 앞의 f가 "중괄호를 변수로 해석하라"는 신호
# - 중괄호 바깥 글자는 그대로 출력
# - 주의: 중괄호 안에는 "변수 이름만" (따옴표 없이!)

name = "홍길동"
age = 25
print(f"{name}님은 {age}살입니다")

code = "EQP-001"
print(f"설비 {code} 점검 완료")

# [핵심] 숫자·문자 함께 출력
# - f-string 안에서는 숫자를 str()로 안 바꿔도 자동으로 끼워짐 (자동 형변환)
print(f"온도: {25}")  # 25를 str()로 감싸지 않아도 그대로 출력됨


# [흔한 실수 진단]
# Q1. 중괄호와 변수 이름이 글자 그대로 출력된다면? -> A. 따옴표 앞에 f를 빠뜨린 것
wrong = "{name}님은 {age}살입니다"  # f가 없으므로 변수가 아니라 글자 그대로 출력
print(wrong)

# Q2. 또 하나의 흔한 실수는? -> A. 중괄호 안에 따옴표를 넣는 것 (예: f"{'name'}" 처럼 X)
# Q3. 진단법은? -> A. 따옴표 바로 앞에 f가 있는지 먼저 확인


print(
    "\n===================== 실습 1. f-string으로 변수 끼워 출력하기 ====================="
)
# 목표: 설비명·온도를 변수로 저장 후 f-string으로 한 줄 출력
# 단계: ① 설비명·온도를 변수로 저장 -> ② f-string으로 예상 결과처럼 출력
# 예상 결과: 설비 PUMP_A, 온도 87도
name = "PUMP_A"
temp = 87
print(f"설비 {name}, 온도 {temp}도")


