# [추가 학습] for 반복문으로 리스트 순회하기
# =====================================================================
# - 리스트의 값을 하나씩 꺼내 인덱스 없이 바로 다루고 싶을 때 for문 사용
# - "for 변수 in 리스트:" 형태로 값이 앞에서부터 하나씩 변수에 담김
machines = ["펌프", "모터", "압축기"]
for m in machines:
    print(f"설비: {m}")

# 인덱스도 함께 필요하면 enumerate() 사용 (인덱스, 값) 쌍으로 꺼내짐
for idx, m in enumerate(machines):
    print(f"{idx}번째 설비: {m}")


