# [문제 상황] 여러 값을 따로 관리할 때의 불편함
# - 변수 하나에 값 하나 - 측정값 100개면 변수 100개 필요
# - 평균·최댓값 계산 시 코드가 값 개수만큼 길어짐
# - 여러 값을 하나로 묶어 다루는 도구가 필요 -> 리스트

# [개념] 리스트 - 값을 담는 목록
# - 여러 값 담기: 변수와 달리 여러 값을 한 목록에 보관
# - 순서 유지: 담은 순서가 그대로 유지돼 나중에 찾기 쉬움


# [개념] 리스트 만들기와 출력 - 대괄호 [ ] 안에 값을 쉼표로 나열해 생성
temps = [25, 26, 24, 28, 27]
print(temps)  # [25, 26, 24, 28, 27]

machines = ["펌프", "모터", "압축기"]  # 글자는 따옴표 필수
print(machines)  # ['펌프', '모터', '압축기']

# [개념] 리스트에 담는 여러 종류의 값
# - 숫자, 글자, 참거짓 값을 한 리스트에 섞어 담기도 가능
# 
# - 다만 분석 실무에서는 같은 종류의 값만 담는 경우가 대부분
mixed = [1, "온도", True]
print(type(mixed[2]))  # <class 'bool'>
print(mixed)  # [1, '온도', True]

# [개념] 빈 리스트와 길이 len()
print(len(temps))  # 5 (담긴 값의 개수)
results = []  # 빈 리스트
print(len(results))  # 0

# [정리] 리스트와 변수의 차이
# 구분      | 변수      | 리스트
# 담는 값   | 값 하나   | 여러 값
# 새 값 넣으면 | 이전 값 사라짐 | 옆에 추가됨
# 순서      | 없음      | 담은 순서 유지
# 비유      | 받침대    | 서랍장


print("\n===================== 실습 1. 나만의 데이터 리스트 만들기 =====================")
# 목표: 여러 값을 대괄호와 쉼표로 리스트에 담고, 출력과 len() 으로 개수 확인하기
# 단계: ① 하루 측정 온도 5개를 리스트로 저장 -> ② print로 전체 출력
#      -> ③ len으로 값 개수를 출력해 5개인지 확인 -> ④ 빈 리스트를 만들어 len이 0인지 확인
# 예상 결과: [25, 26, 29, 30, 35] / 5 / [] / 0
