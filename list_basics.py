temps = [25, 30, 22, 28]
temps.reverse()
print(temps)  # [28, 22, 30, 25]

# [개념] count·index - 세고 찾기
results = ["정상", "이상", "정상", "정상", "이상"]
print(results.count("정상"))  # 3 (몇 개)
print(results.index("이상"))  # 1 (몇 번째)

# [정리] 리스트 메서드 한눈에 정리
# 용도 | 메서드                | 하는 일
# 추가 | append/insert/extend | 끝/위치/묶음 잇기
# 제거 | remove/pop/del        | 값/위치+반환/위치
# 정렬 | sort/reverse          | 크기순/뒤집기
# 탐색 | count/index           | 개수/처음 위치


print("\n===================== 실습 9. 정렬하고 탐색하기 =====================")
# 목표: sort·reverse·count·index로 리스트를 정렬하고 값을 탐색하기
# 단계: ① 온도 리스트를 저장 -> ② sort로 오름차순 정렬해 출력 -> ③ reverse로 뒤집어 출력
#      -> ④ count로 특정 값의 개수와 index로 그 값의 처음 위치를 출력
# 예상 결과: [21, 29, 29, 31, 33, 34, 35] / [35, 34, 33, 31, 29, 29, 21] / 2 / 4
temp_record = [33, 29, 35, 21, 31, 29, 34]
temp_record.sort()
print(temp_record)              # [21, 29, 29, 31, 33, 34, 35]
temp_record.reverse()
print(temp_record)              # [35, 34, 33, 31, 29, 29, 21]
print(temp_record.count(29))    # 2
print(temp_record.index(29))    # 4


