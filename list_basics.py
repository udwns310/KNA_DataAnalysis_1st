# 단계: ① 이상값 999가 있는 리스트 저장 -> ② remove로 이상값을 값 기준으로 제거
#      -> ③ pop으로 특정 위치 값을 꺼내며 제거해 꺼낸 값 출력 -> ④ del로 첫 번째 값을 삭제하고 전체 출력
# 예상 결과: [30, 29, 31, 27, 29] / 꺼낸 값 29 / [31, 27, 29]
