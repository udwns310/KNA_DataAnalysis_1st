# Q1. range(1, 5)를 쓰면 5까지 포함되나요?
# -> A. 아니요. range(시작,끝)도 끝 값은 항상 미포함. range(1,5) -> 1,2,3,4 (4개)
#       "끝-1까지"라고 기억하면 헷갈리지 않음
print(list(range(1, 5)))  # [1, 2, 3, 4]

# Q2. 반복문이 끝난 뒤에도 반복 변수 i를 그대로 쓸 수 있나요?
# -> A. 네. 파이썬은 for 블록 전용 스코프가 따로 없어서, 반복이 끝나도 i는
#       "마지막으로 대입된 값"을 그대로 들고 살아있음 (다른 언어의 블록 스코프와 다른 부분)
for i in range(3):
    pass
print(i)  # 2  (반복이 끝났는데도 마지막 값이 남아있음)

# Q3. range(5, 0, -1)처럼 방향과 증가값이 안 맞으면 오류가 나나요?
# -> A. 아니요. 오류 없이 그냥 "한 번도 실행되지 않는 빈 반복"이 됨 (조용히 넘어가는 함정)
for i in range(0, 5, -1):
    print("실행됨")  # 방향이 안 맞아 한 번도 출력 안 됨
print("반복 끝")  # 이 줄은 항상 실행됨

