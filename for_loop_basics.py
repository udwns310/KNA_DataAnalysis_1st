# [개념] 중첩 반복의 개념 - 반복 안에 반복
for dan in range(2, 4):  # 바깥: 2단, 3단
    for su in range(1, 4):  # 안쪽: 1,2,3
        print(dan, "×", su, "=", dan * su)
    print("---")  # 한 단 끝마다

# [정리] 중첩 반복의 실행 횟수 - 바깥 × 안쪽만큼 통째로 실행됨
# 바깥 횟수 | 안쪽 횟수 | 전체 실행
# 2        | 3        | 6
# 9        | 9        | 81
# 100      | 100      | 10000

# [강사님께 질문하기] 중첩 반복은 바깥×안쪽만큼 실행 횟수가 급격히 늘어나는데,
# 설비 데이터가 수만 건일 때 중첩 반복 대신 실무에서 흔히 쓰는 대안(예: numpy·pandas의 벡터 연산)이 있나요?

# [개념] 반복 코드 실행 추적법 - 표로 회차별 값을 손으로 따라가기
# 회차  | i | 누적 전 | 누적 후
# 시작  | - | -      | 0
# 1회차 | 1 | 0      | 1
# 2회차 | 2 | 1      | 3
# 3회차 | 3 | 3      | 6


print(
    "\n===================== 실습 3. 중첩 반복으로 구구단 출력하기 ====================="
)
# 목표: 중첩 for 로 구구단 전체를 표처럼 출력하기
# 단계: ① 바깥 for 로 2단부터 9단까지 반복 -> ② 안쪽 for 로 각 단에서 1부터 9까지 반복
#      -> ③ 안쪽에서 단·수·곱을 한 줄로 출력 -> ④ 한 단이 끝날 때마다 구분선을 출력
# 예상 결과: 2 × 1 = 2 … 2 × 9 = 18 (구분선) 3 × 1 = 3 …
for tier in range(2, 10):
    for step in range(1, 10):
        print(tier, "×", step, "=", tier * step)
    print("------")


