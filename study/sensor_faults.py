# [개념] 데드밴드의 기록 조건 - 재현
# - 마지막 기록과 일정 폭(데드밴드) 이상 차이 날 때만 새 행이 생김 - 저장 비용은 줄지만
#   그 폭 미만의 미세 변화는 그대로 사라짐
print("\n>>> 0.5도 데드밴드 재현 - 원본 신호와 데드밴드로 걸러진 기록값")
real_signal = [48.0, 48.3, 48.6, 48.2, 48.7, 49.1, 48.8, 49.3, 49.6, 49.2]
recorded = []
last_recorded = real_signal[0]
for v in real_signal:
    if abs(v - last_recorded) >= 0.5:
        last_recorded = v
    recorded.append(last_recorded)
compare = pd.DataFrame({"실제값": real_signal, "데드밴드0.5_기록값": recorded})
print(compare.to_string(index=False))
change_points = sum(1 for i in range(1, len(recorded)) if recorded[i] != recorded[i - 1])
print("변화 기준을 넘어 새로 기록된 횟수:", change_points, "/ 전체", len(real_signal) - 1, "구간")
# - 48.0 -> 48.3(변화폭 0.3, 미기록) -> 48.6(48.0 대비 0.6, 기록) 처럼, 마지막 "기록값"
#   기준으로 0.5도 이상 벌어질 때만 값이 갱신됨 - 그 사이(48.3처럼 작은 변화)는 원본에는
#   있었지만 기록값에는 전혀 남지 않음. 이게 바로 39장 "데드밴드의 기록 조건"에서 말한
#   "저장 비용은 줄지만 기준 폭 미만의 미세 변화는 소실"의 실제 모습

