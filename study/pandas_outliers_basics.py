# [문제 상황] 평균 하나만 믿었다가 생기는 사고
# - 다이캐스팅 202샷 중 단 하나(사이클타임 6170초)가 평균을 완전히 왜곡시킬 수 있음
# - 이런 극단값을 그냥 두고 분석하면 "평균적으로 정상"이라는 착각에 빠지기 쉬움
# - 이 단원의 실데이터: 다이캐스팅(16_diecasting.csv, 202행) - 샷/실린더압력/주조압력/
#   사이클타임/비스킷두께/형체력/상태(0=정상,1=불량), 뒤에서는 용접 데이터로 같은 흐름을 반복

# [개념] 이상치(Outlier)란 - 다른 값들과 동떨어진 값
# - 이상치가 왜 위험한가: 평균처럼 "모두를 더해 나누는" 계산은 극단값 하나에도 크게 흔들림
# - 이상치가 왜 기회인가: 설비 이상·불량의 신호일 수도 있어서 무조건 지우면 안 됨

# [개념] 노이즈성 이상치 vs 신호성 이상치 - 같은 "튀는 값"도 정체가 다름
# - 노이즈성: 센서 순간 튐, 통신 오류 등 실제 현상과 무관한 잡음 - 지워도 정보 손실이 적음
# - 신호성: 진짜 설비 이상·불량을 가리키는 값 - 지우면 정작 봐야 할 신호를 놓치게 됨
# - 그래서 이상치는 "무조건 삭제"가 아니라 "왜 튀었는지 확인 후 판단"이 원칙


print("\n===================== 실습 1. 눈으로 이상치 찾기 =====================")
# 목표: describe()의 min/max/사분위 값을 보고 눈으로 튀는 값을 먼저 짚어보기
# 단계: ① 다이캐스팅 데이터 불러오기 -> ② describe()로 사이클타임 분포 훑기
#      -> ③ max값이 75%(3사분위)보다 얼마나 떨어져 있는지 눈으로 확인
# 예상 결과: 사이클타임 max가 6170으로, 75%(약 36) 근처 값들과 비교가 안 될 만큼 큼
dc = pd.read_csv("data/16_diecasting.csv")
print(dc.shape)  # (202, 7)
print(dc["사이클타임"].describe())
# count 188(결측 14 제외), 75%가 35.9인데 max가 6170.0 - 나머지 값들과 자릿수부터 다름


# [개념] 퍼짐 정도를 재는 세 가지 잣대 - range, 표준편차(std), IQR
# - range(범위) = 최댓값 - 최솟값: 계산은 가장 쉽지만 극단값 하나에 통째로 휘둘림
# - std(표준편차): 평균 중심으로 흩어진 정도 - 이것도 평균을 쓰기 때문에 극단값에 약함
# - IQR(사분위 범위): 가운데 50%만 보기 때문에 양 끝 극단값의 영향을 거의 받지 않음

print("\n===================== 실습 2. range vs std vs IQR 체감하기 =====================")
# 목표: 극단값 3개가 섞인 작은 온도 표본으로 range·std·IQR이 얼마나 다르게 반응하는지 비교
# 단계: ① 정상 범위 온도 15개 + 극단값 3개(-5, 250, 300)로 표본 만들기
#      -> ② range·std·IQR을 각각 계산 -> ③ 극단값 3개를 뺀 표본으로 다시 계산해 차이 비교
# 예상 결과: range는 극단값 유무에 따라 305 -> 13으로 폭락하지만, IQR은 거의 그대로 유지
temp_sample = pd.Series([72, 73, 74, 74, 75, 76, 76, 77, 78, 78, 79, 80, 81, 82, 85, -5, 250, 300])
temp_range = temp_sample.max() - temp_sample.min()
temp_std = temp_sample.std()
temp_q1 = temp_sample.quantile(0.25)
temp_q3 = temp_sample.quantile(0.75)
temp_iqr = temp_q3 - temp_q1
print(round(temp_range, 1), round(temp_std, 1), round(temp_iqr, 1))  # 305 69.0 6.5

temp_clean = temp_sample[~temp_sample.isin([-5, 250, 300])]
clean_range = temp_clean.max() - temp_clean.min()
clean_iqr = temp_clean.quantile(0.75) - temp_clean.quantile(0.25)
print(round(clean_range, 1), round(clean_iqr, 1))  # 13 5.0
# range는 305 -> 13으로 완전히 다른 숫자가 되지만, IQR은 6.5 -> 5.0으로 상대적으로 훨씬
# 적게 움직임 - 극단값이 있는지 없는지조차 range 혼자서는 안정적으로 알려주지 못함

# [강사님께 질문하기] range와 std는 이상치 하나에도 크게 흔들리는데, 그러면 애초에
# 왜 이 둘을 쓰는 건가요? 처음부터 IQR만 쓰면 안 되나요?
# -> 답변: 목적이 다름. range와 std는 "데이터가 극단값까지 포함해서 전체적으로 얼마나
#    넓게 퍼져 있는가"를 보는 잣대라서, 이상치가 실제로 존재한다는 사실 자체를 드러내는
#    데는 오히려 유용함(std가 갑자기 커졌다면 "어딘가 튀는 값이 생겼다"는 신호가 됨).
#    반대로 IQR은 가운데 50%만 보기 때문에 "이상치를 뺀 정상 범위가 어디까지인가"를
#    판단하는 데 적합함. 그래서 실무에서는 std로 "이상 발생 여부"를 감지하고, IQR로
#    "어디까지가 정상 범위인가"를 정하는 식으로 역할을 나눠 씀


# [개념] 사분위수(Quartile) - 데이터를 크기 순으로 줄 세워 4등분하는 경계
# - Q1(25%): 작은 쪽부터 25% 지점 / Q2(50%): 중앙값과 동일 / Q3(75%): 작은 쪽부터 75% 지점
# - pandas의 quantile()은 두 데이터 사이 위치면 두 값을 비율대로 섞어(보간) 계산함

print("\n===================== 실습 3. quantile로 Q1·Q2·Q3 구하기 =====================")
# 목표: 실린더압력의 Q1/Q2/Q3를 quantile()로 직접 계산
# 단계: ① quantile(0.25/0.5/0.75) 호출 -> ② Q2가 median()과 같은 값인지 대조
# 예상 결과: Q1=215.75, Q2=218.0, Q3=265.0
q1 = dc["실린더압력"].quantile(0.25)
q2 = dc["실린더압력"].quantile(0.5)
q3 = dc["실린더압력"].quantile(0.75)
print(q1, q2, q3)  # 215.75 218.0 265.0
print(q2 == dc["실린더압력"].median())  # True - Q2는 median()과 정확히 같은 값


# [개념] IQR과 이상치 경계 공식 - 울타리를 벗어나면 이상치
# - IQR(사분위 범위) = Q3 - Q1
# - 하한(lower) = Q1 - 1.5 x IQR / 상한(upper) = Q3 + 1.5 x IQR
# - 이 울타리 밖의 값을 이상치로 봄 - 1.5배는 통계학에서 오래 쓰여온 경험적 기준값

# [퀴즈] 1.5배가 아니라 1배·3배를 쓰면 어떻게 될지 먼저 예상해보기
# 실린더압력 기준 Q1=215.75, Q3=265.0, IQR=49.25일 때
# - 1배: 하한 166.5, 상한 313.75 (울타리가 좁아짐 -> 이상치로 잡히는 값이 더 많아짐)
# - 1.5배: 하한 141.875, 상한 338.875 (표준)
# - 3배: 하한 68.0, 상한 412.75 (울타리가 넓어짐 -> 웬만한 값은 다 정상으로 통과)
# 정답: 배수가 작을수록 더 예민해져 정상값도 이상치로 오탐하고, 배수가 클수록 둔감해져
#   진짜 이상치도 놓침 - 1.5배는 그 사이에서 실무적으로 자리 잡은 절충값

# [강사님께 질문하기] 1.5배가 "절충값"이라는 건 알겠는데, 그러면 1.5라는 숫자 자체는
# 누가 어떻게 정한 건가요? 데이터마다 최적의 배수가 다를 수도 있지 않나요?
# -> 답변: 1.5는 존 튜키(John Tukey)라는 통계학자가 상자그림(boxplot)을 고안하면서
#    제안한 경험적 기준값. 데이터가 정규분포를 따른다고 가정하면 1.5 x IQR 울타리
#    밖에 실제로 정상값이 들어올 확률이 매우 낮다는 계산에서 나온 숫자라서 "이론적으로
#    완벽한 정답"이라기보다 "여러 데이터에 두루 잘 맞더라"는 관례에 가까움. 말씀하신
#    대로 데이터 특성에 따라 2배·3배를 쓰기도 하고, 아예 도메인 지식(예: 압력계 정상
#    작동 범위)으로 직접 경계를 정하기도 함 - 1.5는 "기본값"이지 "절대값"은 아님


print("\n===================== 실습 4. IQR과 경계값 계산 =====================")
# 목표: 사이클타임의 IQR과 하한·상한을 직접 계산
# 단계: ① Q1·Q3 구하기 -> ② IQR 계산 -> ③ 공식대로 하한·상한 계산
# 예상 결과: IQR 약 15.12, 하한 약 -1.89, 상한 약 58.61
ct_q1 = dc["사이클타임"].quantile(0.25)
ct_q3 = dc["사이클타임"].quantile(0.75)
ct_iqr = ct_q3 - ct_q1
ct_lower = ct_q1 - 1.5 * ct_iqr
ct_upper = ct_q3 + 1.5 * ct_iqr
print(round(ct_iqr, 2), round(ct_lower, 2), round(ct_upper, 2))  # 15.12 -1.89 58.61
# 하한이 음수로 나왔다고 이상한 게 아님 - 사이클타임이 음수가 될 수 없다는 건 사람이
# 아는 지식이고, 공식은 그저 통계적으로 계산할 뿐 - 이런 경우 하한은 실질적으로 0으로
# 봐도 무방하다는 판단은 사람 몫


# [개념] boolean mask로 이상치 탐지하기 - 조건을 만족하는 자리만 True
# - (컬럼 < 하한) | (컬럼 > 상한) 형태로 "울타리 밖"을 한 번에 표시
# - &(그리고)·|(또는)·~(부정)을 쓸 때는 각 조건을 반드시 괄호로 감싸야 함

print("\n===================== 실습 5. boolean mask로 이상치 찾아내기 =====================")
# 목표: 사이클타임 울타리를 벗어난 행을 mask로 골라내기
# 단계: ① mask = (사이클타임 < 하한) | (사이클타임 > 상한) -> ② dc[mask]로 실제 행 확인
# 예상 결과: 6개 행이 걸림 - 그중 5개는 상태=1(불량), 1개는 상태=0(정상)
ct_mask = (dc["사이클타임"] < ct_lower) | (dc["사이클타임"] > ct_upper)
print(dc.loc[ct_mask, ["샷", "사이클타임", "상태"]])
# 샷 147(125.9, 상태0) / 181(652.3, 상태1) / 182(93.1, 상태1) / 191(91.2, 상태1) /
# 196(76.3, 상태1) / 200(6170.0, 상태1)

# [정리] 신호성과 노이즈성이 한 mask 안에 같이 잡힌 실제 사례
# - 상태=1(불량)과 함께 튄 5개는 신호성 이상치일 가능성이 큼 - 실제 불량과 맞물려 있음
# - 샷147은 상태=0(정상)인데도 튐 - 센서가 순간적으로 튄 노이즈성 이상치일 가능성이 큼
# - mask 하나로는 이 둘을 구분 못 함 - 이상치를 찾은 다음에는 상태 같은 다른 컬럼과
#   같이 봐야 신호성인지 노이즈성인지 판단할 수 있음

# [강사님께 질문하기] mask를 만들 때 and/or가 아니라 꼭 &/|를 쓰라고 하셨는데,
# 파이썬 문법으로는 둘 다 "그리고/또는"이라는 뜻 아닌가요? 왜 결과가 달라지나요?
# -> 답변: and/or는 파이썬 기본 불리언 값(True/False) 하나끼리 비교할 때 쓰도록 만들어진
#    연산자라서, "여러 개의 True/False가 줄줄이 들어 있는 Series"를 통째로 넣으면 "이
#    Series 전체를 True로 볼지 False로 볼지 하나만 골라라"는 애매한 요구가 되어 버려
#    ValueError가 남. 반면 &/|는 넘파이/판다스가 "각 자리끼리 하나씩 비교하라"는 뜻으로
#    다시 정의해 둔 연산자라서 Series 전체에 원소 단위로 적용됨. 괄호가 필요한 이유도
#    같은 맥락 - &가 비교 연산자보다 먼저 계산되는 파이썬 우선순위 규칙 때문에, 괄호
#    없이 쓰면 비교가 끝나기도 전에 &부터 계산되어 엉뚱한 결과가 나옴


print("\n===================== 실습 6. 이상치 개수와 비율 =====================")
# 목표: mask.sum()과 mask.mean()으로 이상치 개수·비율을 한 번에 계산
# 단계: ① ct_mask.sum()으로 개수 -> ② ct_mask.mean()*100으로 비율(%)
# 예상 결과: 6건, 약 2.97%
ct_outlier_count = ct_mask.sum()
ct_outlier_ratio = round(ct_mask.mean() * 100, 2)
print(ct_outlier_count, ct_outlier_ratio)  # 6 2.97

cp_mask = (dc["실린더압력"] < q1 - 1.5 * (q3 - q1)) | (dc["실린더압력"] > q3 + 1.5 * (q3 - q1))
print(cp_mask.sum(), round(cp_mask.mean() * 100, 2))  # 6 2.97
# 실린더압력 이상치 6건은 전부 108~113 사이 - 하한(141.875)보다 낮은 쪽으로만 몰려
# 있고, 전부 상태=1(불량) - 압력이 비정상적으로 낮게 나온 샷은 모두 불량으로 이어짐


print("\n===================== 실습 7. boxplot으로 눈으로 확인 =====================")
# 목표: matplotlib 상자그림으로 IQR 계산과 눈에 보이는 상자·수염이 정확히 대응하는지 확인
# 단계: ① 한글 폰트 설정 -> ② boxplot 그리기 -> ③ PNG로 저장 후 확인, 임시 파일은 삭제
