# 중앙값이 가까워짐 - 평균과 중앙값의 격차 자체가 "이상치가 있다"는 신호로 쓰일 수 있음


# [개념] 중복 데이터 - 완전 중복 vs 부분 중복
# - 완전 중복: 모든 컬럼 값이 행 전체에서 똑같은 경우 - 같은 데이터가 실수로 두 번 들어감
# - 부분 중복: 특정 컬럼(예: 샷 번호)만 같고 나머지는 다른 경우 - 같은 대상을 다시
