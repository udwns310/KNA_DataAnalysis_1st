# [문제 상황] 이상치를 찾은 다음엔 어떻게 할 것인가
# - 앞 단원에서 사이클타임·실린더압력의 이상치를 찾아냈음 - 이제 처리 방법이 필요함
# - 처리 방법에 따라 평균 같은 통계가 크게 달라질 수 있어 방법 선택이 곧 분석 방향이 됨

# [개념] 이상치 처리 세 가지 방법 - 상황에 따라 고르는 도구
# - ① 제거: mask로 걸러진 행을 통째로 뺌 - 가장 단순하지만 데이터 손실이 생김
# - ② 경계값 보정(clip): 울타리 밖 값을 울타리 값으로 눌러 앉힘 - 행은 그대로 남음
# - ③ 결측치 변환: 이상치를 NaN으로 바꾼 뒤 중앙값 등으로 채움 - 결측 처리 도구를 재사용

print("\n===================== 실습 1. 이상치 제거 =====================")
# 목표: 사이클타임 이상치 행을 통째로 제거한 뒤 평균이 어떻게 바뀌는지 확인
# 단계: ① dc.dropna(subset=["사이클타임"])로 결측 제외 -> ② ~mask로 이상치 행 제외
#      -> ③ 처리 전후 평균 비교
# 예상 결과: 처리 전 평균 64.75(6170 때문에 왜곡) -> 처리 후 평균 27.28로 정상화
before_mean = round(dc["사이클타임"].mean(), 2)
ct_valid = dc.dropna(subset=["사이클타임"])
ct_mask_valid = (ct_valid["사이클타임"] < ct_lower) | (ct_valid["사이클타임"] > ct_upper)
ct_removed = ct_valid[~ct_mask_valid]
removed_mean = round(ct_removed["사이클타임"].mean(), 2)
print(before_mean, removed_mean)  # 64.75 27.28
print(ct_removed.shape)  # (182, 7)


print("\n===================== 실습 2. 경계값 보정(clip) =====================")
# 목표: 이상치를 지우지 않고 clip()으로 울타리 값에 맞춰 눌러 앉히기
# 단계: ① clip(lower=하한, upper=상한) 호출 -> ② 처리 전후 min/max/평균 비교
# 예상 결과: min은 그대로, max가 6170 -> 58.61로 눌리고, 평균은 28.28
ct_clipped = dc["사이클타임"].clip(lower=ct_lower, upper=ct_upper)
print(dc["사이클타임"].max(), ct_clipped.max())  # 6170.0 58.6125
print(round(ct_clipped.mean(), 2))  # 28.28
# 행 개수는 그대로 유지된다는 점이 제거 방식과 다른 핵심 차이
print(len(dc), ct_clipped.notna().sum())  # 202 188 (원래 결측 14개는 clip해도 여전히 NaN)


print("\n===================== 실습 3. 이상치를 결측치로 바꿔 중앙값 대체 =====================")
# 목표: mask()로 이상치 자리를 NaN으로 비운 뒤 중앙값으로 채우기 - 결측치 단원 도구 재사용
# 단계: ① Series.mask(mask)로 이상치를 NaN 처리 -> ② median() 계산 -> ③ fillna로 채우기
# 예상 결과: NaN이 원래 결측 14개 + 이상치 6개 = 20개로 늘었다가, fillna 후 다시 0개
ct_masked = dc["사이클타임"].mask(ct_mask)
print(ct_masked.isna().sum())  # 20
ct_median = ct_masked.median()
print(ct_median)  # 22.5
ct_filled = ct_masked.fillna(ct_median)
print(ct_filled.isna().sum())  # 0
print(round(ct_filled.mean(), 2))  # 26.8

