# 서로 조금씩 다른데, 이 정도면 어떤 방법을 써도 큰 차이가 없다고 봐도 되나요?
# -> 답변: 이 데이터에서는 세 값이 비슷하게 나왔지만 그건 우연이 아니라 이상치 6개가
#    전체 188개 중 일부일 뿐이라 어떤 방법을 쓰든 나머지 182개 정상값이 평균을 지배하기
#    때문임. 이상치 비율이 지금처럼 3% 안팎일 때는 방법 차이가 작지만, 비율이 20~30%로
#    커지면 세 방법의 결과가 크게 벌어질 수 있음(제거는 표본이 확 줄고, clip은 울타리
#    값에 값이 몰리고, 대체는 중앙값 쪽으로 쏠림). 그래서 "평균이 비슷하니 아무거나
#    써도 된다"가 아니라, 이상치 비율과 분석 목적을 보고 매번 판단해야 함


print("\n===================== 실습 4. 처리 전후 평균·중앙값 비교표 =====================")
