# 단계: ① drop_duplicates(subset=["샷"], keep="last")로 샷 번호 기준 정리
#      -> ② 완전 중복 기준 결과와 행 개수 비교
# 예상 결과: 이번 데이터는 완전 중복=부분 중복이라 결과가 200행으로 동일
