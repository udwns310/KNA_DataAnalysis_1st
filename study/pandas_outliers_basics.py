# [강사님께 질문하기] duplicated()가 중복된 행 2개 모두를 True로 표시하지 않고,
# 나중에 나온 쪽 1개만 True로 표시하는 이유가 있나요?
# -> 답변: duplicated()의 기본 동작은 "먼저 나온 것을 원본으로 보고, 그 뒤에 또 나오는
#    것들을 중복으로 표시"하는 방식(keep="first")이기 때문. 즉 완전히 똑같은 행이 3개
#    있다면 첫 번째는 False(원본 취급), 두 번째·세 번째는 True(중복 취급)가 됨. 이렇게
#    설계된 이유는 "중복을 지운다"는 다음 작업과 바로 이어지도록 하기 위해서임 -
#    True로 표시된 것만 지우면 자동으로 원본 하나만 남기 때문


print("\n===================== 실습 6. keep 옵션으로 기준 바꾸기 =====================")
# 목표: keep="first"/"last"/False 세 가지 기준으로 duplicated 결과가 어떻게 달라지는지 비교
# 단계: ① keep 옵션 3가지로 각각 duplicated() 호출 -> ② True 개수 비교
# 예상 결과: first/last는 각각 2건, False(양쪽 다 표시)는 4건
first_dup = dc.duplicated(keep="first").sum()
last_dup = dc.duplicated(keep="last").sum()
all_dup = dc.duplicated(keep=False).sum()
print(first_dup, last_dup, all_dup)  # 2 2 4
# keep=False는 "원본이든 사본이든 상관없이 겹치는 행은 전부" True로 표시 - 중복 쌍을
# 통째로 눈으로 확인하고 싶을 때 유용


print("\n===================== 실습 7. drop_duplicates로 중복 제거 =====================")
# 목표: drop_duplicates()로 완전 중복 행을 실제로 제거
# 단계: ① drop_duplicates() 호출 -> ② 제거 전후 행 개수 비교 -> ③ 남은 중복이 0인지 재확인
# 예상 결과: 202행 -> 200행, 제거 후 duplicated().sum()은 0
