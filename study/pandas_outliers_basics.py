# 보고 남기는 편이 실무적으로 자연스러움 - 이번 데이터는 중복 행 자체가 완전 중복이라
# first를 쓰든 last를 쓰든 결과가 같지만, 부분 중복(값이 다른 경우)이라면 결과가 갈림


