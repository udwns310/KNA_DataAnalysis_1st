# [개념] f-string 안에서 계산하기
# - 중괄호 안에 계산식을 넣으면 결과가 그대로 들어감
# - f'{hours * 60}분' 처럼 곱셈 결과가 문장에 바로 반영됨
# - 계산을 따로 적지 않아도 문장 안에서 처리됨
# - 단, 복잡한 계산은 미리 변수에 담아두는 게 읽기 좋음

hours = 2
print(f"{hours * 60}분")  # 120분

score1, score2, score3 = 85, 90, 86
print(f"평균 {(score1 + score2 + score3) / 3}")  # 계산식을 중괄호 안에서 바로 사용

average = (score1 + score2 + score3) / 3  # 복잡한 계산은 미리 변수로 빼기
print(f"평균 {average}")


print("\n===================== 실습 2. f-string 안에서 계산하기 =====================")
# 목표: 세 점수를 변수로 저장 -> f-string으로 평균 계산식을 사용해 출력
# 예상 결과: 평균 87.0
a = 80
b = 91
c = 90
print(f"평균 {(a + b + c) / 3}")


# [개념] + 연결 방식과 f-string 비교
# - 같은 문장을 만들 때 f-string이 짧고 안전
# - + 연결은 따옴표·더하기가 많고 숫자마다 str()이 필요
# - f-string은 중괄호 두 개로 끝나서 실수가 적음
# - 실무에서는 문장을 만들 때 거의 항상 f-string 사용
name, temp = "PUMP_A", 87
print("설비 " + name + " 온도 " + str(temp) + "도")  # + 연결: 번거롭고 실수 잦음
print(f"설비 {name} 온도 {temp}도")  # f-string: 짧고 명확


# [개념] f-string 소수점 자리 지정
# - 중괄호 안에 :.Nf 를 붙여 소수점 자릿수 지정
# - {value:.2f} 는 소수점 둘째 자리까지 (자동 반올림)
# - :.1f 는 첫째 자리, :.3f 는 셋째 자리
# - 측정값·평균·비율 정리에 유용
value = 25.34567
print(f"측정값 {value}")  # 25.34567 (자릿수 지정 없음)
print(f"측정값 {value:.2f}")  # 25.35
print(f"측정값 {value:.1f}")  # 25.3


print("\n===================== 실습 3. 소수점 자릿수 지정하기 =====================")
# 목표: f-string 의 :.Nf 로 소수점 자릿수를 지정해 출력
# 단계: ① 측정값 87.456 저장 -> ② 소수점 1자리, 2자리까지 각각 출력
# 예상 결과: 87.5 / 87.46
rate = 87.456
print(f"{rate:.1f}")  # 87.5 (반올림)
print(f"{rate:.2f}")  # 87.46


# =====================================================================
# [추가 학습] f-string 서식(format spec) 더 알아보기
# =====================================================================

# 1) 천 단위 콤마 구분 - 큰 숫자를 보기 좋게
big_number = 1234567
print(f"생산량: {big_number:,}개")  # 1,234,567개

# 2) 퍼센트로 표시 - 0~1 사이 비율을 자동으로 100 곱하고 % 붙임
ratio = 0.8734
print(f"가동률: {ratio:.1%}")  # 87.3%

# 3) 자릿수 맞춰 정렬하기 - 표 형태로 출력할 때 유용
#    < 왼쪽 정렬, > 오른쪽 정렬, ^ 가운데 정렬, 숫자는 최소 폭(자릿수)
for eqp, temp in [("PUMP_A", 87), ("PUMP_B", 5), ("VALVE_1", 123)]:
    print(f"{eqp:<10} 온도 {temp:>4}도")

# 4) 0으로 채워 자릿수 맞추기 - 설비 코드/ID 만들 때 유용
eqp_num = 7
print(f"EQP-{eqp_num:03d}")  # EQP-007

# 5) 디버깅용 = 옵션 - 변수명과 값을 함께 출력 (파이썬 3.8+)
print(f"{value=}")  # value=25.34567
print(f"{value=:.2f}")  # value=25.35
