# - 반복 코드는 (1)화면이 가득 차 흐름이 안 보이고 (2)기준 하나 바꾸려면 모든 자리를 고쳐야 하고
#   (3)복사 중 이름 하나만 안 바꿔도 조용히 틀린 결과를 낸다 - 가장 잡기 어려운 버그 유형

# [개념] 함수란 무엇인가 - 특정 작업을 하는 코드를 묶고 이름을 붙인 것
# - 여러 줄의 코드를 한 묶음으로 보관해 두고, 필요할 때마다 이름만 부르면 됨
# - print, len, type, int - 우리는 이미 함수를 써 왔음 (누군가 미리 만들어 둔 내장 함수)
# - 내가 직접 만들어 이름 붙이는 함수는 사용자 정의 함수

# [강사님께 질문하기] print, len도 다 함수라고 했는데, 제가 직접 만든 함수랑 진짜 똑같이
# 취급되나요, 아니면 뭔가 특별 대우를 받나요?
# -> 답변: 파이썬 입장에서는 특별 대우가 없음. 이름을 부르고 뒤에 괄호를 붙이면 실행된다는
#    점은 내장 함수든 내가 만든 함수든 완전히 동일한 방식. 다른 점은 딱 하나 - 내장 함수는
#    미리 다 만들어져서 바로 쓸 수 있게 제공되는 거고, 내가 만든 함수는 그걸 내가 직접
#    def로 정의해야 한다는 것뿐, 실행되는 원리 자체는 똑같음

# [개념] def 함수의 다섯 부분
# 부분   | 의미                              | 예
