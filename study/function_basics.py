# 단계: ① def와 함수 이름, 괄호, 콜론으로 함수를 정의 -> ② 함수 안 코드를 네 칸 들여써서 실행할 내용 작성
#      -> ③ 함수 정의 아래에서 이름에 괄호를 붙여 호출 -> ④ 여러 번 호출해 매번 실행되는지 확인
