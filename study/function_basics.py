# [개념] 함수를 나누면 좋은 이유 - 각 함수가 한 작업만 해 이해·수정·재사용이 쉬워짐
# - 이해 쉬움: 작게 나누면 이름만 봐도 무슨 일을 하는지 안다
# - 수정 쉬움: 바꿀 부분의 함수만 고치면 된다
# - 재사용 쉬움: 출력 함수가 따로 있으면 다른 작업에서도 가져다 쓴다

# [개념] 입력-처리-출력 사고법 - 함수를 만들기 전에 무엇을 입력받고, 처리하고, 출력할지 먼저 정함
# 함수       | 입력      | 처리   | 출력
# 평균 구하기| 숫자 목록 | 합을 나눔| 평균값
