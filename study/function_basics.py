def calc_average(values):
    return sum(values) / len(values)

def judge(avg):
    if avg > 90:
        return "점검필요"
    return "정상"

avg_result = calc_average([80, 90, 85])
status = judge(avg_result)
print(avg_result, "->", status)  # 85.0 -> 정상


