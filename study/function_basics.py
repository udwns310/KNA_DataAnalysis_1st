# [문제 상황] 같은 인자를 반복해 넣는 번거로움
# - 함수를 부를 때마다 거의 항상 같은 값을 일일이 적어야 하는 번거로움
# - 반복해 적다 보면 오타나 누락 같은 실수가 끼어듦

# [개념] 기본값 인자가 필요한 이유 - 매개변수에 미리 정해 둔 값
# - 인자를 안 주면 미리 정해 둔 기본값이 자동으로 쓰임
# - 인자를 주면 그 값이 덮어쓰며 대신 쓰임 - 유연함이 그대로 유지됨

# [개념] 기본값 인자 정의 방법 - 매개변수 뒤에 =값을 적으면 기본값이 정해짐
def report3(name, value, unit="도"):
    print(name + ": " + str(value) + unit)

report3("압축기A", 75.3)  # unit 생략 -> 기본값 "도"
report3("펌프1", 7.2, "bar")  # "bar"로 덮어쓰기

# [개념] 필수 매개변수와 선택적 매개변수
# - 필수 인자: 기본값 없음, 반드시 인자를 받음 (생략하면 에러)
# - 선택 인자: 기본값 있음, 인자 생략 가능 (안 받으면 기본값, 받으면 받은 값)

# [정리] 기본값이 있는 매개변수의 순서 규칙 - 기본값 없는 매개변수가 앞, 있는 매개변수가 뒤
# def f(a, b, c=0)   가능 - 기본값 없는 것 앞
# def f(a, b=0, c=0) 가능 - 기본값 있는 것 뒤
# def f(a=0, b, c)   불가 - 기본값 있는 것 앞 (정의하는 순간 에러)

# [개념] 기본값을 덮어쓰기 - 기본값이 있는 매개변수에 인자를 넣으면 기본값은 무시되고 넣은 값이 쓰임
def grade(temp, limit=80):
    if temp > limit:
        return "점검필요"
    return "정상"

print(grade(95, limit=90))  # 키워드로 limit=90 -> 기본값 80 대신 90 사용


print("\n===================== 실습 1. 기본값 인자 함수 만들기 =====================")
# 목표: 기본값이 있는 매개변수를 만들고, 생략하면 기본값·넣으면 덮어쓰기를 확인
# 단계: ① def 괄호 안 매개변수에 =로 기본값을 지정 -> ② 인자를 생략하고 호출해 기본값이 쓰이는지 확인
#      -> ③ 인자를 넣어 호출해 기본값을 덮어쓰는지 확인 -> ④ 필수 매개변수는 앞, 기본값 매개변수는 뒤 순서 규칙 확인
# 예상 결과: 78 → 정상 / 95 → 경고 / (limit 덮어쓰면) 50 → 경고
def classify_temp(temp, limit=80):
    if temp > limit:
        return "경고"
    return "정상"

print(classify_temp(78))  # 정상 (기본값 80 사용, 78 <= 80)
print(classify_temp(95))  # 경고 (95 > 80)
print(classify_temp(50, limit=45))  # 경고 (덮어쓴 기준 45 초과)


