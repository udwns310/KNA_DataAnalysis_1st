# report("압축기A", 75.3) -> name="압축기A", temp=75.3
# report(75.3, "압축기A") -> name=75.3,     temp="압축기A" (숫자끼리는 에러 없이 조용히 틀린 결과)
# 위치 인자(positional argument) - 위치에 따라 전달되는 인자

# [주의] 매개변수 개수와 인자 개수
# 매개변수 | 인자 | 결과
# 2개      | 2개  | 정상 동작
# 2개      | 1개  | 인자 부족 에러 (받을 자리는 있는데 줄 값이 없음)
# 2개      | 3개  | 인자 초과 에러 (남는 값을 어디에 둘지 모름)
# 개수 일치 규칙은 번거로워 보여도 값을 빠뜨리거나 잘못 넣으면 즉시 에러로 알려주는 안전장치


