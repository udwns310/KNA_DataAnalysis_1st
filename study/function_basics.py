# [문제 상황] 고정된 값만 쓰는 함수의 한계
# - 함수 안에 값을 고정하면 그 값 하나에만 쓰는 반쪽 함수
# - 설비마다 함수를 새로 만들면 없앤 중복이 값 고정 때문에 되살아남
# - 설비 이름을 함수 밖에서 그때그때 넣어 줄 수 있어야 함수 하나로 모든 설비를 처리 가능

# [개념] 매개변수가 필요한 이유 - 함수가 외부로부터 값을 받는 통로
# - 자판기에 동전을 넣으면 그 동전이 안으로 들어가 작동하듯, 호출 시 값이 매개변수를 통해 들어옴
# - 같은 함수가 받는 값에 따라 다른 일을 함 (믹서기에 사과를 넣으면 사과주스, 딸기를 넣으면 딸기주스)

# [개념] 매개변수와 인자의 차이
# 구분 | 매개변수(parameter)          | 인자(argument)
# 시점 | 함수 정의 시 괄호 안에 적는   | 함수 호출 시 괄호 안에 넣는
# 정체 | 받을 변수(아직 값 없음)       | 실제 값
# 비유 | 택배 받을 주소를 적어 둔 빈 상자| 그 상자에 담겨 오는 물건
def check(name):
    print(name + " 점검을 시작합니다")

check("압축기A")

# [정리] 정의와 호출은 짝을 이룬다
# - 정의할 때 매개변수가 하나면, 호출할 때 인자도 하나를 넣어야 함
# - 안 넣으면 missing argument, 더 넣으면 too many arguments 에러

# [강사님께 질문하기] 함수를 여러 번 호출하면 그때마다 매개변수 자리에 새 값이 채워진다고
# 했는데, 그럼 그 전 호출 때 들어왔던 값은 어디로 가나요?
# -> 답변: 그냥 사라짐. 매개변수는 함수가 끝나면 통째로 없어지는 지역변수라서, 새로
#    호출되면 이전 흔적 없이 완전히 새 값으로 다시 채워짐 - 컵을 매번 비우고 새로 따르는
#    것과 비슷해서, 이전에 뭘 담았었는지는 전혀 안 남고 그 호출과는 완전히 무관하게 동작함

