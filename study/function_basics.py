# Q1. 기본값 인자로 리스트처럼 "계속 바뀔 수 있는 값"을 주면 무슨 일이 생기나요?
# -> A. 기본값은 함수를 "정의할 때" 딱 한 번만 만들어지고, 그 뒤로 호출될 때마다 계속
#       재사용됨 - 매번 호출할 때마다 새로 만들어지는 게 아님. 그래서 리스트처럼 바뀌는
#       값을 기본값으로 쓰면, 이전 호출에서 남긴 흔적이 다음 호출에도 그대로 남아있음
def add_item(item, bucket=[]):
    bucket.append(item)
    return bucket

print(add_item("A"))  # ['A']
print(add_item("B"))  # ['A', 'B']  <- bucket을 새로 안 줬는데 이전 호출 결과가 남아있음!

# -> 안전하게 쓰려면 기본값을 None으로 두고, 함수 안에서 그때그때 새 리스트를 만듦
def add_item_safe(item, bucket=None):
    if bucket is None:
        bucket = []
    bucket.append(item)
    return bucket

print(add_item_safe("A"))  # ['A']
print(add_item_safe("B"))  # ['B']  <- 매번 새 리스트라 이전 흔적이 안 남음

