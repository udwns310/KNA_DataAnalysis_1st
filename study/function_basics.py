print("\n===================== 실습 5. 센서 통계 함수 만들기 =====================")
# 목표: 목록을 받아 여러 통계를 한 번에 돌려주고 언패킹으로 나눠 받기
# 단계: ① 센서값 목록을 매개변수로 받는 함수를 정의 -> ② min·max·합÷개수로 최소·최대·평균을 계산
#      -> ③ 세 값을 쉼표로 함께 return -> ④ 돌려받은 값을 세 변수로 언패킹해 출력
# 예상 결과: 78 92 85.0
def sensor_stats(values):
    return min(values), max(values), sum(values) / len(values)

low2, high2, avg2 = sensor_stats([78, 85, 92])
print(low2, high2, avg2)  # 78 92 85.0


