# 콜론:  | 여기서부터 함수 내용이 시작된다는 표시| :
# 들여쓰기| 이 코드가 함수에 속한다는 표시      | 스페이스 네 칸

# [개념] def 함수의 기본 구조 - 첫 줄에 def 함수이름 괄호 콜론, 둘째 줄부터 들여쓰기
