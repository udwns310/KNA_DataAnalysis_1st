# [개념] 코드 중복을 찾는 눈
# - 복붙 흔적: 값 몇 개만 다른 코드 덩어리가 여러 번 등장
# - 반복 처리: 반복문 안의 처리가 길고 복잡한 경우 - 그 처리를 함수로 빼는 게 깔끔

# [개념] 중복 코드의 모습 - 값만 다르고 구조가 똑같은 코드 덩어리
print("압축기A 온도 확인 중")
print("결과를 기록합니다")
print("펌프1 온도 확인 중")
print("결과를 기록합니다")  # <- 같은 줄 반복!

# [정리] 중복 코드를 함수로 묶는 절차 - 찾기 -> 묶기 -> 교체 -> 확인
# 찾기 | 반복되는 공통 부분을 식별 (값만 다른 같은 구조)
# 묶기 | 그 부분을 def로 함수로 만들어 묶고 이름 정하기
# 교체 | 원래 반복되던 자리를 모두 함수 호출로 바꾸기
# 확인 | 실행해서 결과가 이전과 같은지 검증 (코드 모양은 바뀌어도 동작은 그대로여야 함)

# [주의] 결과 확인을 빠뜨리지 않기
# - 묶기 전 코드의 출력을 먼저 확인해 두고, 묶은 후 다시 실행해 비교
# - 출력이 한 글자라도 다르면 묶는 과정에서 무언가 빠뜨린 것

# [개념] 리팩토링(Refactoring) - 동작은 그대로 두고 구조만 더 좋게 바꾸는 일
# - 사용자가 보기엔 프로그램이 똑같이 작동하지만, 코드 내부는 더 깔끔해진 상태
# - 처음엔 일단 돌아가게 짜고, 작동이 확인되면 중복을 함수로 정리 (전후로 같은 입력에 같은 결과인지 확인)


