print("\n===================== 실습 2. 지역변수 관찰하기 =====================")
# 목표: 함수 안에서 만든 지역변수가 함수 밖에서는 보이지 않음을 확인
# 단계: ① 함수 안에서 새 변수를 만들어 사용 -> ② 함수를 호출해 함수 안에서는 그 변수가 동작하는지 확인
#      -> ③ 함수 밖에서 같은 변수를 출력해 오류가 나는지 확인 -> ④ 함수 안 변수는 함수가 끝나면 사라지는 지역변수임을 정리
# 예상 결과: 함수 안: 30 출력 / 함수 밖에서 접근하면 NameError
def show_local():
    local_result = 30
    print(local_result)  # 30

show_local()
try:
    print(local_result)  # NameError - 함수 밖에는 이 이름이 없음
except NameError as e:
    print("오류 발생:", e)


