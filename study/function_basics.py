# [정리] 좋은 함수 이름의 조건 - 동작·구체성·일관성
# - 동작 표현: 동사로 시작해 하는 일을 드러냄 (check_, get_, print_, calc_)
# - 구체성: 무엇을 다루는지까지 담음 (process 보다 process_sensor_data)
# - 일관성: 비슷한 함수는 비슷한 방식으로 (check_temp / check_pressure)
# - 이름만 잘 지어도 안을 안 봐도 무슨 일을 하는지 알 수 있음 - 주석을 대신함

# [개념] 함수를 여러 번 호출하기 - 부르는 횟수에 제한 없음, 부를 때마다 처음부터 다시 실행
