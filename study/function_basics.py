# 규칙        | 내용                              | 예
# 시작 문자   | 영문자·밑줄로 시작, 숫자로 시작 불가| check_temp(O), 2nd_check(X)
# 사용 문자   | 영문자·숫자·밑줄만, 띄어쓰기 불가   | check_temperature (스네이크 표기법)
# 예약어 회피 | print·if·for 등은 이름으로 못 씀    | -
