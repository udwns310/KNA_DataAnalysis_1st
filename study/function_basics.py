# -> 답변: def문이 실행되는 순간 "이런 이름의 함수가 있다"는 정보가 메모리에 저장됨. 그
#    함수를 한 번도 호출하지 않으면 안의 코드는 실행이 안 될 뿐이고, 프로그램이 끝날
#    때까지 그 정보 자체는 계속 메모리에 남아있음 - 안 쓰는 레시피도 서랍칸 하나를 계속
#    차지하고 있는 셈. 그래서 안 쓰는 함수를 너무 많이 정의해두면 그만큼 자리를 차지함

