# [개념] 지역변수(local variable) - 함수 안에서 만들어져 그 함수 안에서만 쓰이는 변수
# - 함수 안에서는 자유롭게 쓸 수 있지만, 함수 밖에서 출력하려 하면 "모른다"며 에러가 남
# - 불편이 아니라 안전장치: 함수 안 변수가 밖으로 새어 나가지 않아 바깥에 영향을 주지 않음
# - 함수 안 계산 결과를 밖에서 쓰려면 return으로 돌려주면 됨

# [개념] 함수 안 변수와 밖 변수
# - 함수 안에서는 바깥 변수를 읽을 수 있지만, 바깥에서는 함수 안 지역변수를 읽을 수 없음
# - 함수 안에서 바깥 변수와 같은 이름으로 새 변수를 만들면 바깥 변수를 바꾸는 게 아니라
#   함수 안에 별개의 지역변수를 만드는 것

# [강사님께 질문하기] 함수가 끝나면 지역변수가 사라진다고 했는데, 그 값이 있던 자리는
# 그 순간 바로 다시 쓸 수 있게 되는 건가요, 아니면 프로그램이 끝날 때까지 계속 붙잡고
# 있다가 한꺼번에 정리되는 건가요?
# -> 답변: 함수가 끝나는 즉시 그 지역변수들은 더 필요 없다고 표시되고, 파이썬이 알아서
#    그 자리를 회수해서 다른 데 다시 쓸 수 있게 함. 프로그램이 끝날 때까지 안 쓰는 값을
#    계속 붙잡고 있는 게 아니라 함수가 끝나는 그 순간순간 바로바로 정리됨 - 그래서 함수를
#    아무리 많이 호출해도 메모리가 계속 쌓이지 않음

# [개념] 지역변수의 값의 수명 - 호출될 때 생겨나 함수가 끝날 때 사라지고, 다시 부르면 새로 만들어짐
# - 함수는 부를 때마다 깨끗한 상태에서 시작 (이전 호출의 흔적이 안 남음)
# - 이 독립성 덕분에 함수는 언제 불러도 같은 입력에 같은 결과를 냄 (예측 가능성의 바탕)

# [개념] 매개변수도 지역변수다 - 함수 안에서만 살고, 함수가 끝나면 사라짐
# - 차이는 단 하나: 매개변수는 호출될 때 인자로부터 값을 받아 만들어진다는 점

# [개념] 같은 이름 다른 변수 - 두 x는 이름만 같을 뿐 별개의 변수
x = 10
def change_x():
    x = 20  # 함수 안 x (별개)
    print("함수 안 x:", x)

change_x()  # 함수 안 x: 20
