# - 함수에 값을 넣는 것이 입력이라면, 함수가 값을 돌려주는 것이 출력

# [개념] print와 return의 결정적 차이
# 구분     | print       | return
# 하는 일  | 화면에 보여줌| 값을 돌려줌
# 대상     | 사람 눈     | 프로그램
# 이후 사용| 불가능      | 변수 저장 가능
# 함수 실행| 계속됨      | 즉시 종료

# [강사님께 질문하기] return이 있는 함수를 print() 없이 그냥 호출만 하면 어떻게 되나요?
# 값은 계산됐는데 아무 데도 안 담았으니까요.
# -> 답변: 계산은 되지만 그 결과값이 갈 곳이 없어서 그냥 버려짐(화면에 아무것도 안 뜸).
#    print()로 감싸거나 변수에 담지 않으면 return이 돌려준 값을 볼 방법이 없음 - 자판기에서
#    음료가 나왔는데 아무도 안 가져가면 그 자리에 남아있듯, 아무도 안 받으면 그냥 사라짐

# [개념] return 구조와 값 받기 - 함수 안에서 돌려주고 싶은 값 앞에 return을 적음
def add(a, b):
    return a + b

total = add(3, 4)
print(total)  # 7

# [개념] 값을 받는 두 가지 방법
# (1) 변수에 담기: total = add(3, 4) -> 나중에 여러 번 사용
# (2) 바로 쓰기: print(add(10, 20)) -> add가 돌려준 값이 곧장 print로 전달

# [개념] return의 함수 종료 효과 - return을 만나면 값을 돌려주고 바로 함수를 빠져나옴
def check_temp(temp):
    return temp
    print("실행 안 됨")  # <- 이 줄은 영원히 실행되지 않음

print(check_temp(75))  # 75


print("\n===================== 실습 4. 반환값으로 간단 계산기 만들기 =====================")
# 목표: print가 아니라 return으로 결과를 돌려주고 변수에 담기
# 단계: ① 값을 받아 계산하는 함수를 정의 -> ② 계산 결과를 print가 아니라 return으로 돌려주기
#      -> ③ 호출 결과를 변수에 담기 -> ④ 담은 값을 다음 계산·출력에 이어 쓰기
# 예상 결과: 85.0 / 90.0 (담은 값을 이어 씀)
def compute_average(a, b):
    return (a + b) / 2

result = compute_average(80, 90)
print(result)  # 85.0
print(result + 5)  # 90.0 (담은 값을 이어 씀)


# [개념] 여러 값을 한 번에 반환하기 - return 뒤에 쉼표로 나열하면 여러 값이 튜플로 묶임
def min_max(values):
    return min(values), max(values)

pair = min_max([75.3, 88.0, 49.1])
print(pair)  # (49.1, 88.0)

# [개념] 반환값 언패킹으로 받기 - 받는 쪽에서 변수를 쉼표로 나열하면 각 값이 순서대로 따로 담김
low, high = min_max([75.3, 88.0, 49.1])
print(low, high)  # 49.1 88.0

# [주의] 변수 개수와 값 개수를 맞추기 - 언패킹할 때 변수 개수와 돌아오는 값 개수가 같아야 함
# 두 값이 돌아오는데 변수를 세 개 적거나 한 개만 적으면 에러가 남

# [개념] 반환값이 없는 함수와 None - return이 없는 함수도 호출하면 None을 돌려줌
