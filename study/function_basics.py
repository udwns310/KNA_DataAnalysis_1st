# [개념] 괄호는 실행 버튼
# - 이름만 쓴 greet는 "이런 함수가 있다"고 가리키기만 할 뿐 실행은 일어나지 않음
# - 괄호를 붙인 greet() 라야 실행 명령 - 몇 번이든 누를 수 있는 버튼

# [개념] 정의 시점과 호출 시점은 다르다
# - def로 만드는 순간(정의 시점): Python은 기억만 하고 실행 안 함
# - 괄호로 부르는 순간(호출 시점): 함수 코드가 실제로 실행됨
# - 호출이 정의보다 먼저 오면 NameError - 서랍에 넣지도 않은 레시피를 꺼내려는 것과 같음
# greet2()          # NameError: name 'greet2' is not defined
# def greet2():
#     print("...")


