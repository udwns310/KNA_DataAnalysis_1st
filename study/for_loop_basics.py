# 목표: for 안에서 if 로 기준을 넘는 값의 개수 세기
# 단계: ① 측정 횟수를 입력받고 개수 변수를 0으로 준비 -> ② for 로 횟수만큼 돌며 측정값을 입력받기
#      -> ③ if 로 값이 기준(80)을 넘는지 검사해 넘으면 개수를 1 늘리기 -> ④ 반복 뒤 초과 개수를 출력
