#    걸 깜빡하는 실수도 생길 수 있음. enumerate는 그 반복되는 패턴 자체를 아예 이름 붙여
#    미리 만들어둔 것이라, 실수할 여지를 줄이고 코드도 짧아짐 - 자주 쓰는 패턴을 매번 손으로
