#    자리에서 계속 커지는 것 같지만 실제로는 매번 새 값이 만들어지고 이름표만 옮겨 다님
#    (반대로 리스트에 append 하는 건 새로 안 만들고 그 자리에서 진짜로 내용이 바뀌는 경우)

