# while은 조건이 계속 참이면 영원히 안 끝날 수도 있잖아요. 반복 횟수를 미리 몰라도
# for로 표현할 수 있는 경우와, 진짜 while이 아니면 안 되는 경우는 어떻게 구분하나요?
# -> 답변: for도 꼭 "몇 번"이라는 숫자를 미리 알아야만 쓸 수 있는 건 아님. 리스트나
#    파일처럼 "끝이 있는 묶음"을 하나씩 훑어가는 거라면 개수를 몰라도 for로 충분함.
