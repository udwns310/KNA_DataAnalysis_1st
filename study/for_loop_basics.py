# 목표: 중첩 for 로 구구단 전체를 표처럼 출력하기
# 단계: ① 바깥 for 로 2단부터 9단까지 반복 -> ② 안쪽 for 로 각 단에서 1부터 9까지 반복
#      -> ③ 안쪽에서 단·수·곱을 한 줄로 출력 -> ④ 한 단이 끝날 때마다 구분선을 출력
# 예상 결과: 2 × 1 = 2 … 2 × 9 = 18 (구분선) 3 × 1 = 3 …
