# [정리] enumerate - 순서와 값 함께
# 방식      | 코드                   | 얻는 것
# 값 반복    | for t in temps        | 값만 (가장 간단)
# 인덱스     | for i in range(len)   | 인덱스 (값은 따로)
# enumerate | for i, t in enumerate | 인덱스+값 동시
machines = ["펌프", "모터", "압축기"]
for i, m in enumerate(machines):
    print(i, m)  # 0 펌프 / 1 모터 / 2 압축기

# [강사님께 질문하기] enumerate가 순서 번호를 매겨주는 것도 결국 "지금 몇 번째인지" 세는
# 변수를 하나 따로 들고 있다가 값이랑 같이 내보내주는 걸 텐데, 이런 기능은 저희가 직접
# for랑 변수로 만들어 써도 되잖아요. 그런데 왜 파이썬은 이걸 enumerate라는 이름으로
# 따로 만들어 둔 걸까요?
# -> 답변: 맞음, 변수를 하나 만들어서 반복할 때마다 1씩 늘려주는 식으로 직접 구현 가능.
