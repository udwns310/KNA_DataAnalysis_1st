# [강사님께 질문하기] add는 이미 있는 값을 넣으면 그냥 무시한다고 했는데, 그럼 셋에
# 지금 몇 개가 들어있는지 미리 안 세어봐도 add가 "이미 있나 없나"를 어떻게 그렇게
# 빨리 확인하는 거예요? 하나씩 다 비교해보고 있는 건가요?
# -> 답변: 하나씩 다 비교하는 게 아니라, 셋은 값을 넣을 때부터 그 값의 특징을 이용해서
#    "이 값이라면 여기쯤 있어야 한다"는 자리를 미리 계산해서 넣어둠. 그래서 새 값을
#    넣을 때도 그 값의 자리로 바로 가서 이미 뭔가 있는지만 확인하면 되니까, 셋에 값이
#    10개든 100만 개든 확인하는 데 걸리는 시간이 거의 비슷함. 리스트라면 순서대로
#    하나씩 비교해야 해서 값이 많아질수록 오래 걸리는 것과 대비됨

