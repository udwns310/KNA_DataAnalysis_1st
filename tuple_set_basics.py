# [개념] 셋의 두 가지 특징
# - 무순서: 리스트·튜플처럼 0번,1번 순서가 없어 인덱스로 값을 꺼낼 수 없음
# - 무중복: 같은 값은 항상 하나만 유지, "있다·없다"만 따짐

# [강사님께 질문하기] 셋에 값을 넣은 순서랑 화면에 출력됐을 때 나오는 순서가 다를 수
# 있다고 했는데, 그러면 같은 코드를 여러 번 실행해도 매번 출력 순서가 바뀌나요, 아니면
# 한 번 정해지면 그 컴퓨터에서는 항상 같은 순서로 나오나요?
# -> 답변: 완전히 무작위는 아니지만, 우리가 예측하거나 의도적으로 정할 수 있는 순서는
#    아님. 셋은 값을 넣은 순서를 아예 기억하지 않고 각 값을 둘 자리를 다른 방식으로
#    정하기 때문에, 코드에 쓴 순서와 화면에 찍히는 순서가 우연히 같을 수도 다를 수도
#    있음. 그래서 셋을 쓸 때는 "이 순서대로 나올 거야"라고 기대하면 안 되고, 순서가
#    중요한 작업에는 애초에 리스트를 써야 함

# [개념] add로 원소 추가하기 - append와 비슷하지만 이미 있는 값은 조용히 무시함
alerts = {"S01", "S02"}
alerts.add("S03")
print(alerts)
alerts.add("S01")  # 이미 있는 값 - 변화 없음
