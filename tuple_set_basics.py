# [개념] intersection으로 교집합 구하기 - 두 셋에 공통으로 든 값만
print(line_a.intersection(line_b))  # {'S03'} - a & b 와 같은 결과

# [개념] difference로 차집합 구하기 - 한쪽에는 있고 다른 쪽에는 없는 값 (방향에 따라 결과 다름)
print(line_a.difference(line_b))  # {'S01', 'S02'} - a - b
print(line_b.difference(line_a))  # {'S04'} - b - a

# [강사님께 질문하기] A-B랑 B-A가 다르다는 건 이해되는데, 그러면 교집합이나 합집합도
# 순서를 바꾸면(A.intersection(B) vs B.intersection(A)) 결과가 달라지나요?
# -> 답변: 아니요, union과 intersection은 순서를 바꿔도 결과가 똑같음. "전체를 합치는
#    것"이나 "공통된 것만 남기는 것"은 어느 쪽에서 봐도 똑같은 개념이라서 그럼. 반면
#    difference는 "한쪽에서 다른 쪽을 뺀다"는 뜻 자체가 방향을 갖고 있어서(A에서 B를
#    뺀 나머지 vs B에서 A를 뺀 나머지), 방향을 바꾸면 당연히 다른 값이 남는 것. 세
#    연산 중 difference만 순서에 민감하다는 걸 기억해두면 헷갈리지 않음

# [정리] 집합 연산 세 가지 정리
# 합집합 | 합친 전체 | 종류 파악
# 교집합 | 공통인 것 | 공통점 찾기
# 차집합 | 한쪽만   | 변화 추적

# [정리] 집합 연산 활용 - 핵심
# - 두 목록 비교는 합집합·교집합·차집합 세 세트로 완전 분석
# - 전체는 합집합, 공통은 교집합, 차이는 차집합
# - 이 집합 연산은 나중에 Pandas로 두 표를 비교할 때도 그대로 쓰임

# [강사님께 질문하기] 이 합집합·교집합·차집합을 나중에 Pandas로 표(엑셀 같은 데이터)
# 두 개를 비교할 때도 그대로 쓴다고 했는데, 표 데이터는 지금처럼 이름표(문자열) 하나가
# 아니라 여러 정보가 담긴 행 전체일 텐데도 똑같은 방식으로 비교가 되는 거예요?
# -> 답변: 네, 개념은 똑같이 적용됨. 표에서도 보통 "어떤 값으로 각 행을 구별할지"(예:
#    센서 ID)를 정해두고, 그 구별용 값들의 집합을 지금처럼 union·intersection·
#    difference로 비교함. 그렇게 찾은 ID들을 가지고 다시 원래 표에서 해당하는 행
#    전체를 꺼내 오는 식으로 연결됨. 지금 배운 "이름표들의 집합 비교"가, 나중에는
#    "표의 행을 구별하는 집합 비교"로 그대로 확장되는 것


