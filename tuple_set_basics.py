print("\n===================== 실습 2. 튜플 리스트를 반복 처리하기 =====================")
# 목표: (이름, 값) 튜플의 리스트를 for로 순회하며 값을 출력하고, 기준을 넘는 센서를 경고
# 단계: ① 여러 센서를 (이름, 값) 튜플의 리스트로 저장 -> ② for 언패킹으로 이름과 값을 하나씩 꺼내 출력
#      -> ③ if로 값이 기준(90)을 넘으면 경고 출력
