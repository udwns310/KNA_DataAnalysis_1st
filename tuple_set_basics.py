# [개념] 짝지어진 데이터를 하나로 묶기
# - 관련된 데이터는 따로 두지 말고 하나로 묶어 관리
# - 따로 두면 순서가 어긋나는 순간 짝이 깨져 데이터 전체가 망가짐
#   (이름 리스트·값 리스트를 따로 관리하다 순서 하나만 밀려도 엉뚱한 값끼리 묶임)
# - 오늘 배우는 두 도구: 묶는 튜플, 거르는 셋 (다음 시간에 찾는 딕셔너리)

# [개념] 튜플 만들기 - 소괄호 ( ) 안에 값을 쉼표로 구분해 묶으면 튜플이 만들어짐
sensor = ("모터온도", 78)
print(sensor)  # ('모터온도', 78)

# [주의] 단일값 함정 - 값이 하나뿐인 튜플은 반드시 값 뒤에 쉼표가 필요
one = (78,)  # 튜플
not_tuple = (78)  # 그냥 숫자 78 (계산용 괄호로 해석됨)
print(type(one))  # <class 'tuple'>
print(type(not_tuple))  # <class 'int'>

# [강사님께 질문하기] (3, 5)처럼 값이 두 개 이상이면 쉼표가 있어서 딱 봐도 튜플인데,
# 값이 하나일 때만 굳이 쉼표를 꼭 붙여야 하는 이유가, 그때는 괄호만 남아서 계산에
# 쓰는 괄호랑 모양이 똑같아지기 때문인가요?
# -> 답변: 맞음. 값이 여러 개면 괄호 안에 쉼표가 이미 있어서 파이썬이 "이건 값을 묶은
#    거구나" 하고 바로 알 수 있는데, 값이 하나뿐이면 괄호 안에 쉼표가 없어서 그냥 계산
#    순서를 정하는 괄호(예: (2 + 3) * 4)랑 똑같은 모양이 되어버림. 그래서 값이 하나일
#    때만 일부러 쉼표를 남겨서 "이건 튜플이다"라는 표시를 해줘야 함

# [개념] 튜플 인덱싱 - 대괄호 안에 순서 번호를 넣어 값 꺼내기 (0번부터 시작, 음수는 뒤에서부터)
sensor = ("모터온도", 78, "C")
print(sensor[0])  # 모터온도
print(sensor[-1])  # C (전체 길이 몰라도 맨 끝 값)

# [개념] 튜플 슬라이싱 - 콜론으로 구간을 잘라냄 (끝 번호는 미포함)
readings = (78, 80, 79, 95, 77)
print(readings[1:4])  # (80, 79, 95)
print(readings[:3])  # (78, 80, 79) 처음 세 개
print(readings[2:])  # (79, 95, 77) 2번부터 끝까지

# [개념] 튜플 언패킹 - 등호 왼쪽에 변수를 나열하면 튜플 값이 순서대로 담김 (인덱스 불필요)
sensor = ("모터온도", 78)
name = sensor[0]
value = sensor[1]
name, value = sensor  # 언패킹 - 위 두 줄과 같은 결과를 한 줄로
print(name, value)  # 모터온도 78

# [개념] 튜플의 불변성 - 한 번 만들면 값을 바꾸거나 추가·삭제할 수 없음
