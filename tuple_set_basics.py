# [개념] 왜 바꿀 수 없는 튜플을 쓰는가
# - 바꿀 수 없다는 점이 곧 실수로 망가지지 않는 안전장치
# - 실수로 건드리면 그 자리에서 바로 오류로 막아줌
# - 바뀌지 않아 (다음 시간에 배울) 딕셔너리의 키로도 사용 가능

# [강사님께 질문하기] 튜플에 들어있는 값 중 하나가 리스트라면, 그 안쪽 리스트는 튜플이
# 못 바뀌게 막아주는 것과 상관없이 자유롭게 바뀌는 거 아닌가요? 튜플 자체는 못 바꾼다고
# 해도요.
# -> 답변: 맞음. 튜플이 막는 건 "튜플 안의 각 자리가 다른 값을 가리키게 바꾸는 것"뿐이라서,
#    그 자리에 들어있는 값 자체가 리스트처럼 내용을 바꿀 수 있는 값이라면 그 안쪽 내용은
#    얼마든지 바뀔 수 있음. 튜플의 불변성은 "겉으로 보이는 자리가 고정"이라는 뜻이지,
#    "그 안에 든 모든 것이 통째로 얼어붙는다"는 뜻은 아님
record = ("모터온도", [78, 80, 79])
record[1].append(85)
print(record)  # ('모터온도', [78, 80, 79, 85]) - 튜플 자체는 안 바뀌었지만 안쪽 리스트는 바뀜

# [정리] 튜플과 리스트의 차이
# 구분    | 리스트     | 튜플
# 괄호    | 대괄호 [ ] | 소괄호 ( )
# 값 변경 | 가능       | 불가능
# 적합    | 바뀔 값    | 고정 값

# [개념] 튜플 다루기 - len·count·index
status = ("정상", "정상", "경고", "정상")
print(len(status))  # 4 (전체 개수)
print(status.count("경고"))  # 1 (경고 나온 횟수)
print(status.index("경고"))  # 2 (경고가 처음 나온 자리)

# [개념] 여러 센서를 튜플 리스트로 모으기 - 큰 리스트 상자 안에 작은 튜플 상자들
sensors = [
    ("모터온도", 78),
    ("베어링진동", 0.5),
]
print(len(sensors))  # 2

# [개념] 튜플 리스트를 반복문으로 처리하기 - for 언패킹으로 이름과 값 자동 분리
sensors = [("모터온도", 78), ("펌프압력", 95)]
for name, value in sensors:
    if value > 90:
        print(name, "경고")  # 펌프압력 경고

# [개념] 튜플 안의 튜플로 메타데이터 담기 - 인덱스를 두 번 써서 안쪽 값에 접근
sensor = ("모터온도", 78, (3, 5))
print(sensor[2][0])  # 3 (위치 튜플의 가로 좌표)

# [개념] sorted로 튜플 리스트 정렬하기 - 정렬 기준을 튜플 맨 앞에 두면 그 값 기준으로 정렬
sensors = [(78, "모터온도"), (95, "베어링진동"), (32, "펌프압력")]
hot = sorted(sensors, reverse=True)  # 값이 앞이라 값 기준 정렬, reverse=True는 큰 값부터
print(hot[0])  # (95, '베어링진동') 가장 높은 센서

# [강사님께 질문하기] sorted가 튜플의 첫 번째 값 기준으로 정렬한다고 했는데, 만약
# 첫 번째 값이 똑같은 튜플이 두 개 있으면 그다음엔 뭘 기준으로 순서를 정하나요?
# -> 답변: 첫 번째 값이 같으면 자동으로 두 번째 값을 비교해서 순서를 정함. 튜플끼리
#    비교할 때는 첫 자리부터 순서대로 비교하다가 같으면 그다음 자리로 넘어가는 식으로
#    동작하기 때문. 예를 들어 (78, "모터온도")와 (78, "펌프압력")처럼 첫 값이 같으면
#    그다음엔 이름을 기준으로 순서가 갈림
print(sorted([(78, "모터온도"), (78, "펌프압력")]))
# 첫 값이 둘 다 78로 같아서, 두 번째 값(이름)을 기준으로 순서가 정해짐

# [강사님께 질문하기] 리스트도 [3, 5]처럼 좌표를 담을 수 있는데, 굳이 튜플로 (3, 5)라고
# 담는 이유가 스타일 차이인가요, 아니면 실제로 차이가 생기는 상황이 있나요?
# -> 답변: 스타일 차이만은 아님. 좌표처럼 "가로, 세로 두 값"이라는 구조 자체가 절대
#    안 바뀌어야 하는 값이라면, 리스트로 담으면 나중에 실수로 좌표에 값을 하나 더
#    추가하거나 순서를 바꿔버리는 사고가 나도 파이썬이 막아주지 않음. 튜플로 담아두면
#    그런 실수를 아예 오류로 막아줌. 게다가 나중에 배울 딕셔너리에서는 "변하지 않는 값"만
#    키로 쓸 수 있는데 리스트는 안 되고 튜플은 됨 - 좌표를 나중에 딕셔너리 키로 쓰고
#    싶어질 수도 있으니 처음부터 튜플로 담아두면 그런 확장에도 유리함

